def _font(size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.load_default(size=size)


def chart_png() -> bytes:
    """A bar chart drawn as pixels: nothing in it is text for a parser, only a vision model can read it."""
    image = Image.new("RGB", (900, 560), "white")
    draw = ImageDraw.Draw(image)
    draw.text((40, 24), "Revenue by region, 2025 (USD thousand)", fill="black", font=_font(30))
    left, bottom, top = 100, 470, 100
    draw.line([(left, top), (left, bottom), (860, bottom)], fill="black", width=3)
    palette = {"North": "#2f6fb5", "South": "#e08a2b", "West": "#4a9d5b"}
    for index, quarter in enumerate(QUARTERS):
        group = left + 40 + index * 185
        for offset, (region, values) in enumerate(REVENUE.items()):
            height = values[index] * 2
            x = group + offset * 46
            draw.rectangle([x, bottom - height, x + 40, bottom], fill=palette[region])
            draw.text((x + 2, bottom - height - 24), str(values[index]), fill="black", font=_font(18))
        draw.text((group + 40, bottom + 12), quarter, fill="black", font=_font(22))
    for offset, (region, color) in enumerate(palette.items()):
        draw.rectangle([620 + offset * 90, 66, 640 + offset * 90, 86], fill=color)
        draw.text((646 + offset * 90, 64), region, fill="black", font=_font(18))
    buffer = BytesIO()
    image.save(buffer, "PNG")
    return buffer.getvalue()


