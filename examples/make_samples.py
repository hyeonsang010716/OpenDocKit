def xlsx_workbook() -> bytes:
    workbook = openpyxl.Workbook()
    sheet = workbook.active
    sheet.title = "Sales"
    sheet.merge_cells("A1:F1")
    sheet["A1"] = "Sales by region, 2025"
    sheet["A1"].font = Font(bold=True, size=14)
    sheet["A1"].alignment = Alignment(horizontal="center")
    sheet.append(["Region", *QUARTERS, "Share"])
    total = sum(sum(values) for values in REVENUE.values())
    for region, values in REVENUE.items():
        sheet.append([region, *values, sum(values) / total])
    for row in sheet.iter_rows(min_row=3, max_row=5, min_col=2, max_col=5):
        for cell in row:
            cell.number_format = '"$"#,##0"k"'
    for row in sheet.iter_rows(min_row=3, max_row=5, min_col=6, max_col=6):
        row[0].number_format = "0.0%"

    # A second table on the same sheet, separated by an empty row.
    sheet.append([])
    sheet.append(["Largest deals"])
    sheet.append(["Customer", "Closed", "Amount"])
    from datetime import date
    for customer, closed, amount in (("Northwind", date(2025, 3, 14), 48500.0), ("Contoso", date(2025, 9, 2), 73250.5),
                                     ("Fabrikam", date(2025, 11, 20), 39900.0)):
        sheet.append([customer, closed, amount])
    for row in sheet.iter_rows(min_row=9, max_row=11):
        row[1].number_format = "yyyy-mm-dd"
        row[2].number_format = "#,##0.00"

    chart = BarChart()
    chart.title = "Revenue by quarter"
    chart.add_data(Reference(sheet, min_col=2, max_col=5, min_row=2, max_row=5), titles_from_data=True)
    chart.set_categories(Reference(sheet, min_col=1, min_row=3, max_row=5))
    sheet.add_chart(chart, "H2")

    notes = workbook.create_sheet("Notes")
    notes.append(["Figures are in USD thousand."])
    notes.append(["Source: finance ledger, closed 2026-01-05."])
    hidden = workbook.create_sheet("Scratch")
    hidden.append(["internal working data"])
    hidden.sheet_state = "hidden"

    buffer = BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()


def pdf_report() -> bytes:
    """Four pages: a repeated header and page number, a ruled table, a borderless table and body text in two columns."""
    styles = getSampleStyleSheet()
    buffer = BytesIO()

    def furniture(page_canvas: canvas.Canvas, document: BaseDocTemplate) -> None:
        page_canvas.setFont("Helvetica", 9)
        page_canvas.drawString(20 * mm, 285 * mm, "Acme Corporation — Service Level Report")
        page_canvas.drawRightString(190 * mm, 12 * mm, f"Page {document.page}")

    document = BaseDocTemplate(buffer, pagesize=A4, topMargin=25 * mm, bottomMargin=22 * mm, leftMargin=20 * mm, rightMargin=20 * mm)
    width = (A4[0] - 40 * mm - 8 * mm) / 2
    single = Frame(20 * mm, 22 * mm, A4[0] - 40 * mm, A4[1] - 47 * mm, id="single")
    columns = [Frame(20 * mm + index * (width + 8 * mm), 22 * mm, width, A4[1] - 47 * mm, id=f"column{index}") for index in range(2)]
    document.addPageTemplates([PageTemplate(id="single", frames=[single], onPage=furniture),
                               PageTemplate(id="columns", frames=columns, onPage=furniture)])

    story = [Paragraph("Service Level Report", styles["Title"]), Paragraph("1. Availability", styles["Heading1"]),
             Paragraph("Availability is measured per calendar month at the public API gateway. Planned maintenance windows announced "
                       "at least 72 hours ahead are excluded.", styles["BodyText"]), Spacer(1, 6 * mm)]
    ruled = Table([["Service", "Target", "October", "November", "December"], ["API gateway", "99.95%", "99.97%", "99.99%", "99.96%"],
                   ["Web console", "99.90%", "99.93%", "99.88%", "99.95%"], ["Batch exports", "99.50%", "99.71%", "99.64%", "99.80%"]],
                  colWidths=[45 * mm, 25 * mm, 28 * mm, 28 * mm, 28 * mm])
    ruled.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.6, colors.black), ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                               ("ALIGN", (1, 0), (-1, -1), "RIGHT")]))
    story += [ruled, Spacer(1, 8 * mm), Paragraph("2. Incidents", styles["Heading1"]),
              Paragraph("The quarter had three incidents. None breached the monthly target.", styles["BodyText"]), Spacer(1, 4 * mm)]
    borderless = Table([["Date", "Service", "Duration", "Cause"], ["2025-10-08", "Web console", "14 min", "Expired certificate"],
                        ["2025-11-19", "Web console", "52 min", "Database failover"], ["2025-12-02", "Batch exports", "31 min", "Queue backlog"]],
                       colWidths=[30 * mm, 38 * mm, 28 * mm, 55 * mm])
    borderless.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold")]))
    story += [borderless, PageBreak()]

    from reportlab.platypus import NextPageTemplate
    story.insert(-1, NextPageTemplate("columns"))
    paragraphs = [
        "Root cause analysis. The certificate that expired on 8 October had been issued manually and was not covered by the automatic "
        "renewal job. All certificates were moved to automatic renewal on 15 October.",
        "The failover of 19 November was triggered by a storage controller fault. Replication lag at the moment of failover was 4 "
        "seconds, which is within the recovery point objective of 30 seconds.",
        "The export backlog of 2 December followed an unusually large customer job. A per-tenant concurrency limit now prevents one "
        "job from occupying all workers.",
        "Preventive work planned for the next quarter includes a second gateway region, quarterly failover drills and a load test "
        "at three times the December peak.",
    ]
    story.append(Paragraph("3. Analysis", styles["Heading1"]))
    for round_number in range(1, 10):
        story.append(Paragraph(f"3.{round_number} Review round {round_number}", styles["Heading2"]))
        for text in paragraphs:
            story += [Paragraph(text, styles["BodyText"]), Spacer(1, 3 * mm)]
    document.build(story)
    return buffer.getvalue()


def scanned_pdf() -> bytes:
    """One page that is only an image, the way a scanner or a fax produces it: there is no text layer at all."""
    image = Image.new("RGB", (1240, 1754), "white")
    draw = ImageDraw.Draw(image)
    draw.text((120, 130), "NOTICE OF OFFICE RELOCATION", fill="black", font=_font(52))
    lines = ["Reference: ADM-2026-017", "Date: 9 February 2026", "",
             "From 2 March 2026 the Seoul office moves to the 14th floor of", "Harbor Tower, 77 Marine Road.", "",
             "Schedule", "  27 Feb (Fri) 18:00   Packing deadline", "  28 Feb (Sat)         Move by contractor", "  2 Mar (Mon) 09:00    First day at the new office", "",
             "Questions: facilities@example.com, extension 4410."]
    for index, line in enumerate(lines):
        draw.text((120, 260 + index * 62), line, fill="black", font=_font(36))
    picture = BytesIO()
    image.save(picture, "PNG")
    picture.seek(0)

    buffer = BytesIO()
    from reportlab.lib.utils import ImageReader
    page = canvas.Canvas(buffer, pagesize=A4)
    page.drawImage(ImageReader(picture), 0, 0, width=A4[0], height=A4[1])
    page.save()
    return buffer.getvalue()


