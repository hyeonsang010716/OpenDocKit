def epub_book() -> bytes:
    """A two-chapter EPUB 3 written by hand: container → package → spine, with a navigation document that is not content."""
    import zipfile

    def chapter(title: str, body: str) -> str:
        return (f'<?xml version="1.0" encoding="utf-8"?>\n<html xmlns="http://www.w3.org/1999/xhtml"><head><title>{title}</title></head>'
                f"<body><h1>{title}</h1>{body}</body></html>")

    files = {
        "META-INF/container.xml": '<?xml version="1.0"?><container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">'
                                  '<rootfiles><rootfile full-path="OEBPS/book.opf" media-type="application/oebps-package+xml"/></rootfiles></container>',
        "OEBPS/book.opf": '<?xml version="1.0"?><package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="id">'
                          '<metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:identifier id="id">urn:uuid:0</dc:identifier>'
                          "<dc:title>Field Guide to Incident Response</dc:title><dc:creator>Mina Park</dc:creator><dc:language>en</dc:language></metadata>"
                          '<manifest><item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>'
                          '<item id="c1" href="detect.xhtml" media-type="application/xhtml+xml"/>'
                          '<item id="c2" href="respond.xhtml" media-type="application/xhtml+xml"/></manifest>'
                          '<spine><itemref idref="c1"/><itemref idref="c2"/></spine></package>',
        "OEBPS/nav.xhtml": chapter("Contents", '<nav xmlns:epub="http://www.idpf.org/2007/ops" epub:type="toc"><ol>'
                                               '<li><a href="detect.xhtml">Detect</a></li><li><a href="respond.xhtml">Respond</a></li></ol></nav>'),
        "OEBPS/detect.xhtml": chapter("1. Detect", "<p>An incident starts with a <strong>signal</strong>: an alert, a customer report, or a hunch.</p>"
                                                   "<ul><li>Page the on-call engineer</li><li>Open an incident channel</li></ul>"),
        "OEBPS/respond.xhtml": chapter("2. Respond", "<p>Stabilize first, diagnose second. See the "
                                                     '<a href="https://example.com/runbooks">runbook index</a>.</p>'
                                                     "<table><tr><th>Severity</th><th>Response time</th></tr><tr><td>SEV1</td><td>5 minutes</td></tr>"
                                                     "<tr><td>SEV2</td><td>30 minutes</td></tr></table>"),
    }
    buffer = BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(zipfile.ZipInfo("mimetype"), "application/epub+zip")  # first and uncompressed, as the format requires
        for name, text in files.items():
            archive.writestr(name, text, compress_type=zipfile.ZIP_DEFLATED)
    return buffer.getvalue()


def convert_with_libreoffice() -> None:
    """Save the Office samples in the formats only an office suite writes: OpenDocument, RTF and the 97-2003 binaries.

    Needs LibreOffice (`soffice` on PATH). Without it these samples are left as they are in the repository.
    """
    import shutil
    import subprocess
    import tempfile

    soffice = shutil.which("soffice") or shutil.which("libreoffice")
    if soffice is None:
        print("LibreOffice not found: the .odt/.ods/.odp/.rtf/.doc/.ppt samples were not rebuilt")
        return
    jobs = [("quarterly-report.docx", "odt", "quarterly-report.odt"), ("quarterly-report.docx", "rtf", "quarterly-report.rtf"),
            ("quarterly-report.docx", "doc", "quarterly-report.doc"), ("sales.xlsx", "ods", "sales.ods"),
            ("launch-plan.pptx", "odp", "launch-plan.odp"), ("launch-plan.pptx", "ppt", "launch-plan.ppt")]
    with tempfile.TemporaryDirectory() as folder:
        for source, target, name in jobs:
            subprocess.run([soffice, "--headless", "--norestore", f"-env:UserInstallation=file://{folder}/profile", "--convert-to", target,
                            "--outdir", folder, str(SAMPLES / source)], check=True, capture_output=True, timeout=120)
            data = (Path(folder) / f"{Path(source).stem}.{target}").read_bytes()
            (SAMPLES / name).write_bytes(data)
            print(f"{name:28} {len(data):>8,} bytes  (LibreOffice)")


