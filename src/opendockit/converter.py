# The message of a conversion that ran out of memory or time (`IsolatedConverter`, and running out of memory on a picture here).
TOO_COMPLEX_MESSAGE = "The document is too large or too complex to convert."
_DEFAULT_OPTIONS = ConvertOptions()
_ZIP_FORMATS = {DocumentFormat.DOCX, DocumentFormat.PPTX, DocumentFormat.XLSX, DocumentFormat.HWPX, DocumentFormat.ODT, DocumentFormat.ODS,
                DocumentFormat.ODP, DocumentFormat.EPUB}
# Formats where the original whitespace (code indentation, table alignment) carries meaning. Spaces inside a line are not collapsed.
_KEEP_SPACES = {DocumentFormat.TEXT, DocumentFormat.MARKDOWN}
# Alt text that Office and Hangul (HWP) attach automatically ("그림 3" (picture 3), "image1.png", "그림입니다. 원본 그림의 이름…"
# (this is a picture. name of the original picture…)) carries no information.
# Office's auto-generated alt text ("로고, 폰트이(가) 표시된 사진\n\n자동 생성된 설명", "A picture containing …\n\nDescription
# automatically generated", and in newer versions "AI 생성 콘텐츠는 정확하지 않을 수 있습니다." / "AI가 생성한 콘텐츠는 부정확할 수
# 있습니다." (AI-generated content may be incorrect)) is not author information either. Kept as author alt text, it went into the
# describer prompt and remained as '[Image: …]' even after the picture was judged decorative. Text saved without the trailing line is
# dropped only when it is a single line in a form only Office uses ('이(가) 표시된 사진/그림', 'A picture containing') and what precedes
# it is a comma-separated list of words Office picked (at most three words per item, lowercase in English) — text where the author
# added a line or wrote a sentence ('A picture containing our CEO John Smith …') is kept.
# A form like 'A screenshot of a computer' without the trailing line cannot be told from human writing, so it is not included
# (Pinned by: test_image.py::TestOfficeAutoGeneratedAltText).
# The trailing line is looked for once per run of line breaks (`\S[^\S\n]*\n\s*+`: the text before it ends in something other than
# whitespace — the caller strips the alt text — and the whitespace up to the line is taken whole, without giving any back). Written
# as `.+\n\s*`, it was looked for after every line break of a run, skipping the rest of the run each time: alt text with 16,000
# line breaks took 2.4 seconds. The same alt text matches (Pinned by: test_audit_core.py::TestAltTextWithManyLineBreaks).
_OFFICE_KO_TAG = r"[\w\-]+(?:[ \t]+[\w\-]+){0,2}"
_OFFICE_EN_TAG = r"(?-i:[a-z][a-z\-']*(?:[ \t]+[a-z][a-z\-']*){0,2})"
_USELESS_ALT = re.compile(
    r"^(?:(?:그림|사진|이미지|개체|picture|image|img|figure|graphic|chart)\s*\d*|.+\.(?:png|jpe?g|gif|bmp|wmf|emf|tiff?)"
    r"|그림입니다.*"
    rf"|{_OFFICE_KO_TAG}(?:,[ \t]*{_OFFICE_KO_TAG})*이\(가\)\s*표시된\s*(?:사진|그림)"
    rf"|a[ \t]+picture[ \t]+containing[ \t]+{_OFFICE_EN_TAG}(?:,[ \t]*{_OFFICE_EN_TAG})*"
    r"|.*\S[^\S\n]*\n\s*+(?:자동\s*생성된\s*설명|description\s+automatically\s+generated|description\s+generated\s+with\s+[\w ]+confidence"
    r"|AI\s*생성\s*콘텐츠는\s*정확하지\s*않을\s*수\s*있습니다|AI가\s*생성한\s*콘텐츠는\s*부정확할\s*수\s*있습니다"
    r"|AI-generated\s+content\s+may\s+be\s+incorrect)\.?)$",
    re.IGNORECASE | re.DOTALL,
)
_CONTEXT_CHARS = 400
# Length of the tail carried along while collecting the preceding body text. Generous, so that _CONTEXT_CHARS remain even after
# trailing whitespace is stripped.
_CONTEXT_WINDOW = _CONTEXT_CHARS * 4
# Piece size of `read_limited` after its first read (a stream that hands out less than asked for).
_READ_CHUNK = 1024 * 1024


def convert(data: bytes | bytearray | memoryview, filename: str | None = None,
            options: ConvertOptions | None = None) -> ConversionResult:
    """Convert document bytes into Markdown ready for LLM input.

    This is synchronous CPU work. On an event loop, use `aconvert`.
    Images are extracted into `result.images` and the body keeps only placeholder text. To fill in the image content as text,
    use `aconvert(..., describer=...)` or `describe_images`.
    Every failure is a `ConversionError` subclass (the message is fixed English wording that can be shown to the user). `data` is
    bytes, bytearray or memoryview; any other type (a path string, Path, file object) is a `TypeError` — for a path use `convert_file`.
    """
    data = _content_bytes(data)
    _check_arguments(filename, options)
    options = options or _DEFAULT_OPTIONS
    check_size(data, options)

    # Format detection is parsing too: it opens ZIP and OLE containers. It sits inside the same boundary as extraction: an encrypted
    # ZIP (RuntimeError) or an unknown compression method (NotImplementedError) leaked out as an exception outside ConversionError
    # (Pinned by: test_converter.py::test_zip_that_cannot_be_inspected_is_a_conversion_error).
    document_format = None
    try:
        document_format = detect_format(data, filename)
        if document_format in _ZIP_FORMATS:
            _guard_zip(data, options)
        key = hashlib.sha256(data).hexdigest()[:16]
        with marker_key(key):
            document_format, extraction = _extract(document_format, data, filename, options)
    except ConversionError:
        raise
    except Exception as exc:  # the boundary that gathers arbitrary parser-library exceptions into one conversion failure.
        subject = f"the {document_format.value.upper()} document" if document_format else "the file format"
        raise CorruptedDocumentError(f"Could not parse {subject}. The file may be corrupted.") from exc

    warnings = list(extraction.warnings)
    mismatch = extension_mismatch(document_format, filename)
    if mismatch:
        warnings.insert(0, mismatch)

    collapse = document_format not in _KEEP_SPACES
    sections = []
    for section in extraction.sections:
        template = clean_text(section.text, collapse_spaces=collapse)
        # Section headings (sheet and slide titles) are cleaned like the body. With a title in decomposed jamo, the result was not NFC
        # (Pinned by: test_converter.py::TestAssembly::test_sheet_and_slide_titles_are_normalized_to_nfc).
        title = " ".join(clean_text(section.title).split()) if section.title else section.title
        if template or section.kind is SectionKind.SLIDE:
            sections.append(Section(section.kind, section.index, "", title, template))

    # If the text alone is already over the limit, the pictures are not decoded. Decoding, downscaling and the vision-model calls
    # after them would all be wasted.
    text_chars = sum(solid_length(section.template) for section in sections)
    exceeded = extraction.exceeded or (options.max_chars is not None and text_chars > options.max_chars)
    images, fallbacks = _prepare_images([] if exceeded else extraction.images, sections, options, warnings, key)
    result = ConversionResult(format=document_format, text="", sections=sections, metadata=dict(extraction.metadata),
                              images=images, base_warnings=warnings, options=options, fallbacks=fallbacks,
                              exceeded=exceeded, counted=max(extraction.chars, text_chars) if exceeded else 0,
                              marker_key=key, time_limited=extraction.time_limited)
    return render(result)


def check_size(data: bytes, options: ConvertOptions) -> None:
    """The size checks that come before anything is parsed: over `max_file_bytes` is `DocumentTooLargeError`, empty is
    `CorruptedDocumentError`. `IsolatedConverter` runs them in the server process too, so an oversized upload is not copied
    into a worker first (Pinned by: test_isolated.py::TestIsolatedConverter::test_oversized_or_empty_input_is_refused_before_a_worker_starts)."""
    if len(data) > options.max_file_bytes:
        raise DocumentTooLargeError(f"The file is too large (maximum {_size_text(options.max_file_bytes)}).")
    if not data:
        raise CorruptedDocumentError("The file is empty.")


def read_limited(stream: BinaryIO, limit: int, *, size_hint: int | None = None) -> bytes:
    """At most `limit + 1` bytes of `stream`: enough for `convert` to tell that the content is over `limit`, without reading
    the rest. A file whose size the file system does not report (a pipe, `/dev/zero`, a stream of a remote file system) was
    read to its end before the size limit applied: `opendockit /dev/zero` grew without bound
    (Pinned by: test_converter.py::TestReadingWithinTheSizeLimit). `size_hint` is the size the file system reports for a
    regular file: the first read asks for exactly that much (one piece, as `read_bytes` did), later reads go in 1 MiB pieces."""
    chunks: list[bytes] = []
    total = 0
    while total <= limit:
        wanted = size_hint + 1 if size_hint is not None and not chunks else _READ_CHUNK
        chunk = stream.read(min(wanted, limit + 1 - total))
        if not chunk:
            break
        chunks.append(chunk)
        total += len(chunk)
    return b"".join(chunks)


def _size_text(size: int) -> str:
    """A size limit in whole megabytes (`50MB`), or below 1 MiB in kilobytes or bytes (`512KB`, `10 bytes`) — in megabytes alone a
    limit under 1 MiB read 'maximum 0MB' (Pinned by: test_audit_core.py::TestSizeLimitBelowOneMegabyte)."""
    if size >= 1024 * 1024:
        return f"{size // (1024 * 1024)}MB"
    return f"{size // 1024}KB" if size >= 1024 else f"{size} bytes"


def _content_bytes(data: bytes | bytearray | memoryview) -> bytes:
    """Take the file content as bytes. A memoryview failed in format detection (`startswith`) and a path string failed during
    detection, and both were rejected with 'The file may be corrupted', which hid the cause (Pinned by: test_converter.py::TestInputTypes)."""
    if isinstance(data, bytes):
        return data
    if isinstance(data, (bytearray, memoryview)):
        return bytes(data)
    raise TypeError(f"convert takes the file content as bytes (got {type(data).__name__}). For a file path, use convert_file.")


def _check_arguments(filename: object, options: object) -> None:
    """Check the types of the file name and options before converting. Passing the options in the file-name position, as in
    `convert(data, ConvertOptions(...))`, raised a TypeError only after the whole conversion had run (minutes for a large PDF)
    (Pinned by: test_core_mbox_markdown_and_api.py::TestArgumentsInTheWrongPlace)."""
    if isinstance(filename, ConvertOptions):
        raise TypeError("The second argument is the file name. Pass the options by keyword, as options=ConvertOptions(...).")
    if filename is not None and not isinstance(filename, str):
        raise TypeError(f"The file name must be a str (got {type(filename).__name__}).")
    if options is not None and not isinstance(options, ConvertOptions):
        raise TypeError(f"options must be a ConvertOptions (got {type(options).__name__}).")


def _extract(document_format: DocumentFormat, data: bytes, filename: str | None,
             options: ConvertOptions) -> tuple[DocumentFormat, Extraction]:
    """Call the extractor. UTF-8 text that was detected as PDF but does not read as one (a note explaining the PDF structure) is
    read again as text (`detect.pdf_lookalike_text_format`). Other rejections, such as password or size, are left as they are."""
    try:
        return document_format, EXTRACTORS[document_format](data, options)
    except Exception as exc:
        if document_format is not DocumentFormat.PDF or (isinstance(exc, ConversionError)
                                                          and not isinstance(exc, CorruptedDocumentError)):
            raise
        fallback = pdf_lookalike_text_format(data, filename)
        if fallback is None:
            raise
        return fallback, EXTRACTORS[fallback](data, options)


def convert_file(path: str | os.PathLike[str], options: ConvertOptions | None = None) -> ConversionResult:
    """Convert the file at `path`. A regular file over `max_file_bytes` is refused from its size before it is read; anything
    else (a pipe, a device) is read only up to the limit (`read_limited`). A path that cannot be opened is an `OSError`."""
    file_path = Path(path)
    _check_arguments(None, options)
    options = options or _DEFAULT_OPTIONS
    with file_path.open("rb") as stream:
        status = os.fstat(stream.fileno())
        if stat.S_ISREG(status.st_mode) and status.st_size > options.max_file_bytes:
            raise DocumentTooLargeError(f"The file is too large (maximum {_size_text(options.max_file_bytes)}).")
        data = read_limited(stream, options.max_file_bytes,
                            size_hint=status.st_size if stat.S_ISREG(status.st_mode) else None)
    return convert(data, file_path.name, options)


async def aconvert(data: bytes | bytearray | memoryview, filename: str | None = None,
                   options: ConvertOptions | None = None, *,
                   executor: Executor | None = None, describer: "ImageDescriber | None" = None,
                   max_concurrency: int = 8) -> ConversionResult:
    """Run `convert` off the event loop and, if there is a `describer`, fill in the images as text.

    Once the character count goes over `options.max_chars`, it stops right there: if the text alone is over, the images are
    neither decoded nor described, and if it goes over during description, the remaining images are not sent. The result's
    `exceeded` tells.
    Without an `executor`, the default thread pool is used. Conversion is mostly pure-Python parsing (PDF, HWP), so it holds the
    GIL for a long time. A server with many concurrent uploads should pass a `ProcessPoolExecutor` to keep other requests
    responsive (the arguments and the result are all picklable).
    Image description is network calls, so they are sent from the event loop `max_concurrency` at a time.
    """
    loop = asyncio.get_running_loop()
    data = _content_bytes(data)  # a memoryview cannot be sent to a process pool (not picklable)
    _check_arguments(filename, options)
    result = await loop.run_in_executor(executor, partial(convert, data, filename, options))
    if describer is None or not result.images:
        return result

    from opendockit.describe import describe_images

    return await describe_images(result, describer, max_concurrency=max_concurrency)


def render(result: ConversionResult) -> ConversionResult:
    """Put descriptions or placeholder text into the image places of the section originals (template) and render the full text again."""
    options = result.options
    images = {image.id: image for image in result.images}
    pattern = image_marker_pattern(result.marker_key)
    sections = [replace(section, text=_render_template(section.template, images, result.fallbacks, pattern))
                for section in result.sections]

    text = _assemble(sections, options)
    warnings = list(result.base_warnings)
    failed = sum(1 for image in result.images if image.failed)
    if failed:
        warnings.append(f"{failed} image(s) could not be described (the vision model call failed) and were left as placeholder text.")
    unread_pages = [image for image in result.images if image.kind is ImageKind.PAGE and not image.description]
    if unread_pages:
        pages = ", ".join(str(image.section_index) for image in unread_pages[:10])
        warnings.append(f"{len(unread_pages)} page(s) whose text exists only as an image "
                        f"({pages}{' and more' if len(unread_pages) > 10 else ''}) "
                        "are empty because they did not go through image description (OCR).")

    # Whether the limit is exceeded is counted exactly on the text rendered here. If the extraction stage stopped first, the value
    # counted up to then (counted) is larger than the limit. `result.exceeded` is not simply carried over: before description the
    # result can be over because of the `[Image]` placeholders and then drop under the limit once pictures are removed as decoration.
    char_count = max(len(text), result.counted)
    exceeded = options.max_chars is not None and char_count > options.max_chars
    # Whether nothing was extracted is decided before the cut: with `max_chars=0` text that was cut to nothing was also reported as
    # 'No text was extracted.' (Pinned by: test_audit_core.py::TestWarningsWhenNoCharactersAreAllowed).
    empty = not text.strip()
    if exceeded and options.max_chars is not None:
        text = text[: options.max_chars].rstrip()
        sections = _cut_sections(sections, options, options.max_chars)
        warnings.append(f"The conversion was stopped because the text exceeded {options.max_chars:,} characters.")
    if empty:
        warnings.append("No text was extracted.")
    return replace(result, text=text, sections=sections, warnings=warnings, exceeded=exceeded, char_count=char_count)


def _prepare_images(raw_images: list[RawImage], sections: list[Section], options: ConvertOptions,
                    warnings: list[str], marker: str) -> tuple[list[DocumentImage], dict[int, str]]:
    """Decode and downscale, filter out small images, repeated images (logos) and duplicates, and build the list of images to
    describe and the placeholder texts.

    An empty placeholder text means the placeholder is removed (decoration). An image to describe gets its description in place
    of the placeholder text.
    """
    fallbacks: dict[int, str] = {}
    prepared = []
    # The same picture (a stamp or logo placed on every page) is decoded only once. Even when the outcome is an exception (dropped,
    # undecodable), it is the same for the same picture (Pinned by: test_image.py::test_same_picture_is_decoded_once).
    decoded: dict[tuple[bytes, bool], tuple[PreparedImage, str] | ImageSkipped | ImageUnreadable] = {}
    for raw in raw_images:
        # Placeholder text goes in after cleaning (clean_text), so it is cleaned into one line here. NFD and line breaks stayed as
        # they were and broke table rows.
        alt = " ".join(clean_text(raw.alt).split()) if raw.alt and not _USELESS_ALT.match(raw.alt.strip()) else None
        key = (raw.data, raw.kind is not ImageKind.STANDALONE)
        if key not in decoded:
            try:
                image = prepare_image(raw.data, min_side=options.min_image_side, max_side=options.image_max_side,
                                      filter_decorations=key[1])
                decoded[key] = (image, hashlib.sha256(image.data).hexdigest())
            except (ImageSkipped, ImageUnreadable) as outcome:
                decoded[key] = outcome
            except MemoryError as exc:
                # Not a broken picture but a document too large for the memory there is (`image.prepare_image`)
                # (Pinned by: test_image.py::TestOutOfMemoryWhileReadingAPicture).
                raise DocumentTooLargeError(TOO_COMPLEX_MESSAGE) from exc

        outcome = decoded[key]
        if isinstance(outcome, ImageTooLarge) and raw.kind is ImageKind.STANDALONE:
            # A size problem, not corruption. A very large picture that cannot be read reduced (not a JPEG, or over the decode
            # limit even at 1/8) (Pinned by: test_core_image_and_assembly.py::TestVeryLargePictures).
            raise DocumentTooLargeError("The image is too large (decode limit about 179 million pixels). Reduce its resolution or "
                                        "save it as JPEG and upload it again.") from outcome
        if isinstance(outcome, ImageUnreadable) and raw.kind is ImageKind.STANDALONE:
            # The uploaded file is that one picture. Reject it like any other corrupted file — it used to come back as a success
            # whose body was just '[Image]'
            # (Pinned by: test_image.py::TestStandaloneImage::test_uploaded_image_that_cannot_be_decoded_is_rejected_as_corrupted).
            if needs_heif_plugin(raw.data):
                raise UnsupportedFormatError('Reading HEIC/HEIF images needs an optional dependency. '
                                             'Install it with: pip install "opendockit[heic]"') from outcome
            message = "Could not read the image. The file may be corrupted or may be an unsupported image format."
            raise CorruptedDocumentError(message) from outcome
        if isinstance(outcome, ImageSkipped):
            fallbacks[raw.id] = ""
        elif isinstance(outcome, ImageUnreadable):
            fallbacks[raw.id] = _image_fallback(alt)
        else:
            prepared.append((raw, alt, *outcome))

    # A picture that could not be decoded remains only as placeholder text. Say that content is missing (the same picture is counted
    # once). Pictures left out for being too large are reported separately — reported as 'WMF/EMF or corrupted', nobody could tell it
    # was the size (Pinned by: test_core_mbox_markdown_and_api.py::TestTooLargePictureInsideADocument).
    too_large = sum(1 for outcome in decoded.values() if isinstance(outcome, ImageTooLarge))
    unreadable = sum(1 for outcome in decoded.values() if isinstance(outcome, ImageUnreadable)) - too_large
    if unreadable:
        warnings.append(f"{unreadable} image(s) are in an unreadable format (WMF/EMF vectors, etc.) or corrupted "
                        "and were left as placeholder text.")
    if too_large:
        warnings.append(f"{too_large} image(s) are too large (decode limit about 179 million pixels) and were left as placeholder text.")

    counts: dict[str, int] = {}
    for _, _, _, digest in prepared:
        counts[digest] = counts.get(digest, 0) + 1

    candidates: list[tuple[RawImage, str | None, PreparedImage]] = []
    first_of: dict[str, int] = {}
    aliases: dict[int, int] = {}

    for raw, alt, image, digest in prepared:
        if raw.kind is ImageKind.FIGURE and counts[digest] >= options.repeated_image_threshold:
            fallbacks[raw.id] = ""
            continue
        if digest in first_of:
            # The same picture appearing again below the repeat threshold is switched to the first one's placeholder, so it is
            # described once and the description goes into both places. The second place used to be erased and the picture
            # vanished from that page or slide (Pinned by: test_image.py::TestSamePictureTwice).
            # If the first one has no alt text, the alt text of the later one is used.
            index = first_of[digest]
            first, first_alt, first_image = candidates[index]
            aliases[raw.id] = first.id
            candidates[index] = (first, first_alt or alt, first_image)
            continue
        first_of[digest] = len(candidates)
        candidates.append((raw, alt, image))

    for raw, alt, _ in candidates:
        fallbacks[raw.id] = "" if raw.kind is ImageKind.PAGE else _image_fallback(alt)

    if aliases:
        _point_aliases_at_first(sections, aliases, marker)

    # Over the limit, whole-page images (scanned pages — the only content of that page) are picked before pictures.
    chosen = {raw.id for raw, _, _ in sorted(candidates, key=lambda item: item[0].kind is not ImageKind.PAGE)
              [: options.max_images]}
    over_limit = len(candidates) - len(chosen)
    locations = _locate_markers(sections, image_marker_pattern(marker))
    images: list[DocumentImage] = []
    for raw, alt, image in candidates:
        if raw.id not in chosen:
            continue
        section, context = locations.get(raw.id, (None, ""))
        images.append(DocumentImage(
            id=raw.id, data=image.data, mime_type=image.mime_type, width=image.width, height=image.height, tiles=image.tiles,
            kind=raw.kind, section_kind=section.kind if section else SectionKind.DOCUMENT,
            section_index=section.index if section else 1, alt=alt, context=context,
        ))

    if over_limit:
        warnings.append(f"There are many images, so only {options.max_images} were selected for description (scanned pages first) "
                        f"and {over_limit} were left as placeholders only.")
    return images, fallbacks


def _point_aliases_at_first(sections: list[Section], aliases: dict[int, int], marker: str) -> None:
    """Among the placeholders in the section originals, change the numbers in `aliases` to the number of the first occurrence of the
    same picture. The limit decision during description counts the placeholder occurrences and multiplies the bound on the
    increase by that (`describe.describe_images`), so both places are counted."""
    pattern = image_marker_pattern(marker)
    with marker_key(marker):
        def point(match: re.Match[str]) -> str:
            image_id = int(match.group(1))
            return image_marker(aliases[image_id]) if image_id in aliases else match.group(0)

        for index, section in enumerate(sections):
            sections[index] = replace(section, template=pattern.sub(point, section.template))


def _locate_markers(sections: list[Section], pattern: re.Pattern[str]) -> dict[int, tuple[Section, str]]:
    """Image id → (the section it is in, part of the body text right before it).

    The preceding text is built by joining the text between placeholders and carrying only the tail. Rescanning the whole front
    of the section for every placeholder takes (number of pictures × body length) on a single-section document with many
    pictures (HWP, DOCX) (19 seconds for 16,384 pictures).
    """
    locations = {}
    for section in sections:
        tail, position = "", 0
        for match in pattern.finditer(section.template):
            tail = (tail + section.template[position:match.start()])[-_CONTEXT_WINDOW:]
            position = match.end()
            locations.setdefault(int(match.group(1)), (section, tail.strip()[-_CONTEXT_CHARS:]))  # first place, if the picture appears several times
    return locations


def _render_template(template: str, images: dict[int, DocumentImage], fallbacks: dict[int, str],
                     pattern: re.Pattern[str]) -> str:
    if "⟦IMG:" not in template:
        return template

    lines: list[str] = []
    fenced = _fenced_lines(template)
    for index, line in enumerate(template.split("\n")):
        ids = [int(found) for found in pattern.findall(line)]
        if not ids:
            lines.append(_FENCED_LINE + line if index in fenced else line)
            continue
        row = line.strip()
        markup = row.startswith("<tr>") and row.endswith("</tr>")
        if markup or (len(row) > 1 and row.startswith("|") and row.endswith("|")):
            # Inside a table cell: a table row has to be one line, so fold it into one line. An HTML table (a table with merged
            # cells, markdown.TableGrid) is escaped as HTML. A table row is recognized only as a line that starts and ends with `|`
            # (the `| … |` of render_table/TableGrid, and `|a|b|` with no spaces around the cells in a Markdown source) or as
            # `<tr>…</tr>`. Looking at the start only, a paragraph starting with `|` or `<tr>` was read as a table row and the
            # picture description was folded onto one line
            # (Pinned by: test_converter.py::TestAuditedAssemblyGaps::test_paragraph_that_starts_like_a_table_row_gets_a_picture_block).
            # Looking only for lines ending in `… |`, a picture in a Markdown `|a|b|` table cell became a paragraph picture and
            # the table broke in two (Pinned by: test_core_text_and_mail.py::TestPictureInACompactMarkdownTable).
            # Known accepted gap: a paragraph of the form `|…|` is still a table row.
            lines.append(pattern.sub(lambda match: _cell_text(images, fallbacks, int(match.group(1)), html=markup), line))
            continue

        # Inside a paragraph (or on a line of its own): leave the text as it is and put the image block below it. The placeholder,
        # together with the spaces around it, becomes one space, the leading indentation of the line (the nested-list level) is
        # kept, and a blank line follows the block — without it the next line continued into the quote block
        # (Pinned by: test_converter.py::TestAssembly::test_picture_block_inside_a_paragraph_is_followed_by_a_blank_line,
        # test_picture_in_nested_list_item_keeps_the_item_indentation).
        # The line is cut at the placeholders and the spaces are stripped from the pieces: one pattern for 'spaces, placeholder,
        # spaces' started again at every space of a run, so a line with 80,000 spaces before a picture took 4 seconds
        # (Pinned by: test_audit_core.py::TestSpacesOnALineWithAPicture).
        pieces, position = [], 0
        for match in pattern.finditer(line):
            pieces.append(line[position:match.start()])
            position = match.end()
        body = " ".join(piece.strip(" ") for piece in [*pieces, line[position:]]).strip()
        text = line[: len(line) - len(line.lstrip())] + body if body else ""
        blocks = [block for block in (_block_text(images, fallbacks, image_id) for image_id in ids) if block]
        lines.append("\n\n".join(part for part in [text, *blocks] if part) + ("\n" if blocks else ""))
    return _collapse_blank_lines("\n".join(lines)).strip()


# A mark attached during rendering to lines inside a code fence (a private-use character — `clean_text` has already removed it,
# so it is not in the body).
_FENCED_LINE = "\ue030"


def _fenced_lines(template: str) -> set[int]:
    """Line numbers inside paired code fences (``` or ~~~). Pairing is `markdown.code_fences`, the one `clean_text` uses (what
    follows an unpaired opening fence is outside)."""
    return code_fences(template.split("\n")).inside


def _collapse_blank_lines(text: str) -> str:
    """Reduce runs of two or more blank lines to one, but leave the lines inside a code fence (marked `_FENCED_LINE`) as they are
    and remove the mark.

    `\\n{3,}` → `\\n\\n` was applied to the whole section, so only in sections holding a picture the consecutive blank lines inside
    a code block that `clean_text` had kept (two lines between functions) were reduced to one
    (Pinned by: test_core_image_and_assembly.py::TestBlankLinesInCodeNextToAPicture). It only reduces, so the character bound
    (`image_length_bound`) still holds.
    """
    lines: list[str] = []
    for line in text.split("\n"):
        if line.startswith(_FENCED_LINE):
            lines.append(line[len(_FENCED_LINE):])
        elif line or not lines or lines[-1]:
            lines.append(line)
    return "\n".join(lines)


def image_length_bound(image: DocumentImage, fallbacks: dict[int, str]) -> int:
    """The most the character count of `render` can grow when this picture goes from the erased (decorative) state to its current state.

    A placeholder becomes a block (`_block_text`) in a paragraph and one line (`_cell_text`) in a table cell, and gets one blank
    line before the block (2 characters) and the line break that makes the blank line after it (1 character). Merging blank
    lines and trimming surrounding whitespace only reduce the count. When the placeholder of one picture appears several times,
    the caller multiplies by the count. `describe` uses this value to skip rendering the document, so if it were smaller than
    the real value, an exceeded limit would be missed
    (Pinned by: test_image.py::TestResourceBounds::test_description_stops_at_exactly_the_image_that_crosses_the_limit).
    A picture that is erased now (decorative, no alt text) has not grown at all: 0. Counted as the 3 characters of the blank
    lines it no longer has, every SKIP answer used up headroom, so in a document just under the limit the whole text was
    assembled again every few pictures — quadratic in the number of pictures, on the event loop (2,000 pictures: 2.6 s)
    (Pinned by: test_core_image_and_assembly.py::TestDecorativeAnswersNearTheLimit).
    """
    if _erased(image):
        return 0
    images = {image.id: image}
    return max(len(_block_text(images, fallbacks, image.id)), len(_cell_text(images, fallbacks, image.id)),
               len(_cell_text(images, fallbacks, image.id, html=True))) + 3


def _erased(image: DocumentImage | None) -> bool:
    """Whether this picture was judged decorative and is to be erased from its place. If the author attached alt text, it is not
    erased and the placeholder text ('[Image: …]') stays — it is information a person wrote
    (Pinned by: test_image.py::TestDecorativePictureWithAltText)."""
    return image is not None and image.decorative and not image.alt


def _image_fallback(alt: str | None) -> str:
    """`[Image: alt]` (or `[Image]`) for a picture that stays as placeholder text. The brackets of the alt text are escaped like link
    text (`_inline._escape_link_text`), as the extractors do for pictures they do not extract: an alt such as
    `a](https://evil.example) [b` made the placeholder a working link (Pinned by:
    test_audit_web_fixes.py::TestAltTextCannotMakeALink::test_alt_text_of_an_extracted_picture). The describer still gets the alt
    text as written."""
    return f"[Image: {_escape_link_text(alt)}]" if alt else "[Image]"


def _block_text(images: dict[int, DocumentImage], fallbacks: dict[int, str], image_id: int) -> str:
    image = images.get(image_id)
    if image is None or not image.description:
        return "" if _erased(image) else fallbacks.get(image_id, "")
    if image.kind is ImageKind.PAGE:
        return f"<!-- Text read from image -->\n{image.description}"
    lines = image.description.split("\n")
    lines[0] = f"[Image] {lines[0]}"
    return "\n".join(f"> {line}" if line.strip() else ">" for line in lines)


def _cell_text(images: dict[int, DocumentImage], fallbacks: dict[int, str], image_id: int, *, html: bool = False) -> str:
    """The text of a picture inside a table cell (one line). In a Markdown cell `|` separates cells, so it becomes `\\|`
    (Pinned by: test_converter.py::TestAssembly::test_alt_text_is_escaped_in_table_cells_and_normalized); in an HTML cell only
    the table tags are neutralized, as for cell text (test_picture_in_an_html_table_cell_keeps_its_text)."""
    image = images.get(image_id)
    if image is None or not image.description:
        lines = ["" if _erased(image) else fallbacks.get(image_id, "")]
    else:
        lines = [line.strip() for line in image.description.split("\n") if line.strip()] or [""]
        lines[0] = f"[Image] {lines[0]}"
    if html:
        return "<br>".join(neutralize_table_tags(line) for line in lines)
    return "<br>".join(lines).replace("|", "\\|")


def _guard_zip(data: bytes, options: ConvertOptions) -> None:
    """Zip-bomb defense: check the total uncompressed size first, from the central directory."""
    try:
        total = uncompressed_size(data)
    except zipfile.BadZipFile as exc:
        raise CorruptedDocumentError("The document's archive structure is corrupted.") from exc
    if total > options.max_uncompressed_bytes:
        raise DocumentTooLargeError("The document becomes too large when decompressed.")


def _assemble(sections: list[Section], options: ConvertOptions) -> str:
    return _layout(sections, options)[0].strip()


def _layout(sections: list[Section], options: ConvertOptions) -> tuple[str, list[int]]:
    """The text of the joined sections (before the surrounding whitespace is trimmed) and where each section body starts in it."""
    parts: list[str] = []
    starts: list[int] = []
    position = 0

    for section in sections:
        header = _header(section, options)
        part = "\n\n".join(piece for piece in (header, section.text) if piece)
        if part and parts:
            position += 2
        starts.append(position + (len(part) - len(section.text)))
        if part:
            parts.append(part)
            position += len(part)

    return "\n\n".join(parts), starts


def _header(section: Section, options: ConvertOptions) -> str:
    if section.kind is SectionKind.PAGE:
        return f"<!-- Page {section.index} -->" if options.page_markers else ""
    return section_heading(section)


def section_heading(section: Section) -> str:
    """The heading the full text gives a slide or a sheet (`## Slide 2: Goals`, `## Sheet: Sales`); '' for a page or a whole
    document. For callers that hand out sections one by one (the integrations) and want each to say what it is."""
    if section.kind is SectionKind.SLIDE:
        return f"## Slide {section.index}" + (f": {section.title}" if section.title else "")
    if section.kind is SectionKind.SHEET:
        return f"## Sheet: {section.title}" if section.title else f"## Sheet {section.index}"
    return ""


def _cut_sections(sections: list[Section], options: ConvertOptions, limit: int) -> list[Section]:
    """Cut the section bodies at the same point where `text` was cut for going over the limit. The body of a section that starts
    after the cut is empty text.

    Over the limit, only `text` was cut and everything stayed in `sections`, so code using the sections (chunking, source
    attribution) received content beyond the limit
    (Pinned by: test_converter.py::TestAuditedAssemblyGaps::test_sections_are_cut_where_the_text_is_cut and 2 more). The section
    list and `template` are left as they are — when descriptions are filled in again, `render` renders from the originals and
    counts the characters again.
    """
    joined, starts = _layout(sections, options)
    cut = len(joined) - len(joined.lstrip()) + limit
    return [replace(section, text=section.text[:max(cut - start, 0)].rstrip())
            for section, start in zip(sections, starts, strict=True)]
