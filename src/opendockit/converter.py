def convert(data: bytes | bytearray | memoryview, filename: str | None = None,
            options: ConvertOptions | None = None) -> ConversionResult:
    """Convert document bytes into Markdown ready for LLM input.

    This is synchronous CPU work. On an event loop, use `aconvert`.
    Images are extracted into `result.images` and the body keeps only placeholder text. To fill in the image content as text,
    use `aconvert(..., describer=...)` or `describe_images`.
    Every failure is a `ConversionError` subclass (the message is fixed English wording that can be shown to the user); a
    library needed for the file that cannot be imported (a broken installation) is an `ImportError` with a fixed sentence. `data` is
    bytes, bytearray or memoryview; any other type (a path string, Path, file object) is a `TypeError` — for a path use `convert_file`.
    """
    # Running out of memory anywhere in a conversion is 'too large or too complex', here as under `IsolatedConverter`, and
    # never 'corrupted': a MemoryError inside an extractor (a page of a multi-page TIFF, a picture of a PDF) was gathered
    # with the parser failures into `CorruptedDocumentError`, and one after extraction left `convert` as it was. A
    # `ConversionError` raised from one counts too (`_ran_out_of_memory`). The copy of a bytearray or memoryview and the
    # checks before the conversion are inside as well — the copy of a 50 MB upload is the first thing that can fail; a wrong
    # argument is the `TypeError` it was (Pinned by: test_converter.py::TestRunningOutOfMemory).
    try:
        data = _content_bytes(data)
        _check_arguments(filename, options)
        options = options or _DEFAULT_OPTIONS
        check_size(data, options)
        return _converted(data, filename, options)
    except MemoryError as exc:
        raise DocumentTooLargeError(TOO_COMPLEX_MESSAGE) from exc
    except ConversionError as exc:
        if str(exc) != TOO_COMPLEX_MESSAGE and _ran_out_of_memory(exc):
            raise DocumentTooLargeError(TOO_COMPLEX_MESSAGE) from exc
        raise


def _ran_out_of_memory(exc: BaseException) -> bool:
    """Whether a MemoryError is among the causes and contexts of `exc` (each exception visited once): a parser that wraps it
    in its own exception, which the converter wraps again, was reported as a corrupted document
    (Pinned by: test_image.py::TestOutOfMemoryWhileReadingAPicture::test_memory_error_deeper_in_the_chain_is_too_complex)."""
    seen: set[int] = set()
    waiting: list[BaseException] = [exc]
    while waiting:
        current = waiting.pop()
        if id(current) in seen:
            continue
        seen.add(id(current))
        if isinstance(current, MemoryError):
            return True
        waiting.extend(link for link in (current.__cause__, current.__context__) if link is not None)
    return False


def _converted(data: bytes, filename: str | None, options: ConvertOptions) -> ConversionResult:
    """`convert` after its argument and size checks."""
    # Format detection is parsing too: it opens ZIP and OLE containers. It sits inside the same boundary as extraction: an encrypted
    # ZIP (RuntimeError) or an unknown compression method (NotImplementedError) leaked out as an exception outside ConversionError
    # (Pinned by: test_converter.py::test_zip_that_cannot_be_inspected_is_a_conversion_error).
    document_format = None
    own_dictionary()  # before any parse of lxml in this thread (`_xml.own_dictionary`)
    try:
        document_format = detect_format(data, filename)
        if document_format in _ZIP_FORMATS:
            _guard_zip(data, options)
        key = hashlib.sha256(data).hexdigest()[:16]
        with marker_key(key), span_budget():
            document_format, extraction = _extract(document_format, data, filename, options)
    except MemoryError:
        raise
    except ImportError as exc:
        # A reader library that cannot be imported is a broken installation, not a corrupted document: imported on first use,
        # it was reported as corrupted for every valid file of its format. It goes up with the fixed sentence of
        # `extractors.load`, which an import a library makes of its own while it reads gets too
        # (Pinned by: test_converter.py::TestReaderThatCannotBeImported).
        if str(exc) == IMPORT_FAILED_MESSAGE:
            raise
        raise ImportError(IMPORT_FAILED_MESSAGE) from exc
    except Exception as exc:  # the boundary that gathers arbitrary parser-library exceptions into one conversion failure.
        # A ZIP format that could not be read while parts of it carry the ZIP password bit (`zip -e`) is password-protected, not
        # corrupted: zipfile refuses every encrypted part, so the extractors found the parts they need missing or unreadable
        # (Pinned by: test_converter.py::TestPasswordProtectedZip). A part that is only skipped (one picture, one slide) leaves the
        # document readable and changes nothing.
        if isinstance(exc, ConversionError) and not isinstance(exc, CorruptedDocumentError):
            raise
        if document_format in _ZIP_PASSWORD_MESSAGES and has_password_protected_part(data):
            raise EncryptedDocumentError(_ZIP_PASSWORD_MESSAGES[document_format]) from exc
        if isinstance(exc, ConversionError):
            raise
        subject = f"the {document_format.value.upper()} document" if document_format else "the file format"
        raise CorruptedDocumentError(f"Could not parse {subject}. The file may be corrupted.") from exc

    warnings = list(extraction.warnings)
    mismatch = extension_mismatch(document_format, filename)
    if mismatch:
        warnings.insert(0, mismatch)

    collapse = document_format not in _KEEP_SPACES
    # In a code or data file the line and paragraph separators are characters of a string (`"x\u2028y"` in JSON) and stay; made
    # line breaks, a JSON string held a raw line break (Pinned by: test_markdown.py::TestCleanText::
    # test_line_separators_of_code_and_data_files_stay).
    separators = not (document_format is DocumentFormat.TEXT and any("\u2028" in section.text or "\u2029" in section.text
                                                                     for section in extraction.sections)
                      and code_or_data_text(data, filename))
    sections = []
    for section in extraction.sections:
        template = clean_text(section.text, collapse_spaces=collapse, line_separators=separators)
        # Section headings (sheet and slide titles) are cleaned like the body. With a title in decomposed jamo, the result was not NFC
        # (Pinned by: test_converter.py::TestAssembly::test_sheet_and_slide_titles_are_normalized_to_nfc).
        # As one line (`clean_line`), not as a text of its own: a title is written after `## Slide 1: `, where no fence can
        # open, and cleaned as a text a title that starts with tildes or backticks got the backslash of a fence line
        # (`## Slide 1: \~~~ 감사합니다 ~~~`)
        # (Pinned by: test_converter.py::TestAssembly::test_title_or_alt_text_that_starts_like_a_fence_gets_no_backslash).
        title = clean_line(section.title) if section.title else section.title
        if template or section.kind is SectionKind.SLIDE:
            sections.append(Section(section.kind, section.index, "", title, template))

    # A ZIP format that was read without an error but gave nothing at all — no text, no slide title, no picture — while parts of
    # it are password-protected: those parts were its content, which zipfile refused to read. The extractors skip a part they
    # cannot read with a warning (a slide, a sheet), so a deck whose slides alone were protected came back as an empty success
    # (Pinned by: test_converter.py::TestPasswordProtectedZip::test_protected_slides_are_an_encrypted_document). A document that
    # gives anything stays a document whose protected parts were skipped.
    if (document_format in _ZIP_PASSWORD_MESSAGES and not extraction.images
            and not any(section.template.strip() or section.title for section in sections) and has_password_protected_part(data)):
        raise EncryptedDocumentError(_ZIP_PASSWORD_MESSAGES[document_format])

    # If the text alone is already over the limit, the pictures are not decoded. Decoding, downscaling and the vision-model calls
    # after them would all be wasted. They keep their placeholder text all the same (`_placeholders_only`), as they do when
    # decoding is turned off (`decode_images=False`): the alt text an author gave a picture stays in the text
    # (Pinned by: test_converter.py::TestPlaceholdersWithoutDecoding).
    text_chars = sum(solid_length(section.template) for section in sections)
    exceeded = extraction.exceeded or (options.max_chars is not None and text_chars > options.max_chars)
    if exceeded or not options.decode_images:
        images, fallbacks = [], _placeholders_only(extraction.images, options)
    else:
        images, fallbacks = _prepare_images(extraction.images, sections, options, warnings, key)
    result = ConversionResult(format=document_format, text="", sections=sections, metadata=_clean_metadata(extraction.metadata),
                              images=images, base_warnings=warnings, options=options, fallbacks=fallbacks,
                              exceeded=exceeded, counted=max(extraction.chars, text_chars) if exceeded else 0,
                              marker_key=key, time_limited=extraction.time_limited)
    return render(result)


def _clean_metadata(metadata: dict[str, str]) -> dict[str, str]:
    """The document metadata as clean one-line values (`markdown.clean_line`: NFC, invisible and control characters removed,
    whitespace and line breaks collapsed to one space); a value left empty is dropped.

    Metadata was handed over as the file wrote it: a title in decomposed jamo was not NFC, a zero-width space or control
    characters stayed in it, and an author with line breaks (`a\nb\n# Heading`) put Markdown lines into whatever template
    printed it (Pinned by: test_converter.py::TestMetadataIsCleaned).
    """
    cleaned = {key: clean_line(value) if isinstance(value, str) else value for key, value in metadata.items()}
    return {key: value for key, value in cleaned.items() if value != ""}


def check_size(data: bytes, options: ConvertOptions) -> None:
    """The size checks that come before anything is parsed: over `max_file_bytes` is `DocumentTooLargeError`, empty is
    `CorruptedDocumentError`. `IsolatedConverter` runs them in the server process too, so an oversized upload is not copied
    into a worker first (Pinned by: test_isolated.py::TestIsolatedConverter::test_oversized_or_empty_input_is_refused_before_a_worker_starts)."""
    if len(data) > options.max_file_bytes:
        raise DocumentTooLargeError(f"The file is too large (maximum {_size_text(options.max_file_bytes)}).")
    if not data:
        raise CorruptedDocumentError("The file is empty.")


def read_limited(stream: BinaryIO, limit: int, *, size_hint: int | None = None) -> bytes:
    """At most `limit + 1` bytes of `stream`: enough for `convert` to tell that the content is over `limit`, without reading
    the rest. A file whose size the file system does not report (a pipe, `/dev/zero`, a stream of a remote file system) was
    read to its end before the size limit applied: `opendockit /dev/zero` grew without bound
    (Pinned by: test_converter.py::TestReadingWithinTheSizeLimit). `size_hint` is the size the file system reports for a
    regular file: the first read asks for exactly that much (one piece, as `read_bytes` did), later reads go in 1 MiB pieces."""
    chunks: list[bytes] = []
    total = 0
    while total <= limit:
        wanted = size_hint + 1 if size_hint is not None and not chunks else _READ_CHUNK
        chunk = stream.read(min(wanted, limit + 1 - total))
        if not chunk:
            break
        chunks.append(chunk)
        total += len(chunk)
    return b"".join(chunks)


def _size_text(size: int) -> str:
    """A size limit in whole megabytes (`50MB`), or below 1 MiB in kilobytes or bytes (`512KB`, `10 bytes`) — in megabytes alone a
    limit under 1 MiB read 'maximum 0MB' (Pinned by: test_audit_core.py::TestSizeLimitBelowOneMegabyte)."""
    if size >= 1024 * 1024:
        return f"{size // (1024 * 1024)}MB"
    return f"{size // 1024}KB" if size >= 1024 else f"{size} bytes"


def _content_bytes(data: bytes | bytearray | memoryview) -> bytes:
    """Take the file content as bytes. A memoryview failed in format detection (`startswith`) and a path string failed during
    detection, and both were rejected with 'The file may be corrupted', which hid the cause (Pinned by: test_converter.py::TestInputTypes)."""
    if isinstance(data, bytes):
        return data
    if isinstance(data, (bytearray, memoryview)):
        return bytes(data)
    raise TypeError(f"convert takes the file content as bytes (got {type(data).__name__}). For a file path, use convert_file.")


def _check_arguments(filename: object, options: object) -> None:
    """Check the types of the file name and options before converting. Passing the options in the file-name position, as in
    `convert(data, ConvertOptions(...))`, raised a TypeError only after the whole conversion had run (minutes for a large PDF)
    (Pinned by: test_core_mbox_markdown_and_api.py::TestArgumentsInTheWrongPlace)."""
    if isinstance(filename, ConvertOptions):
        raise TypeError("The second argument is the file name. Pass the options by keyword, as options=ConvertOptions(...).")
    if filename is not None and not isinstance(filename, str):
        raise TypeError(f"The file name must be a str (got {type(filename).__name__}).")
    if options is not None and not isinstance(options, ConvertOptions):
        raise TypeError(f"options must be a ConvertOptions (got {type(options).__name__}).")


def _extract(document_format: DocumentFormat, data: bytes, filename: str | None,
             options: ConvertOptions) -> tuple[DocumentFormat, Extraction]:
    """Call the extractor. UTF-8 text that was detected as PDF but does not read as one (a note explaining the PDF structure) is
    read again as text (`detect.pdf_lookalike_text_format`). Other rejections, such as password or size, are left as they are."""
    # Without decoding, a PDF is read without drawing its pictures and pages, and an image file, which is nothing but its picture,
    # is not read: the placeholders a PDF picture would leave carry no alt text, and drawing them is the cost the option is
    # for (`ConvertOptions.decode_images`; Pinned by: test_converter.py::TestPlaceholdersWithoutDecoding).
    if not options.decode_images and document_format in (DocumentFormat.PDF, DocumentFormat.IMAGE):
        options = replace(options, extract_images=False)
    # A note that lists a whole PDF (a tutorial on the format) reads as that PDF, so trying it says nothing: the note was lost and
    # only the listing's 'Hello World' came back. Named as text, with other text before the header and UTF-8 throughout, it is
    # text; a real PDF named so would need bytes in front of its header and no binary byte anywhere
    # (Pinned by: test_detect.py::TestTextThatLooksLikeAPdf::test_note_listing_a_readable_pdf_is_read_as_its_name_says).
    if document_format is DocumentFormat.PDF and named_as_text(filename):
        fallback = pdf_lookalike_text_format(data, filename)
        if fallback is not None:
            return fallback, EXTRACTORS[fallback](data, options)
    try:
        return document_format, EXTRACTORS[document_format](data, options)
    except Exception as exc:
        # A PDF reader that cannot be imported says nothing about the file: it is not tried as text (`_converted`)
        if document_format is not DocumentFormat.PDF or isinstance(exc, ImportError) or (isinstance(exc, ConversionError)
                                                          and not isinstance(exc, CorruptedDocumentError)):
            raise
        fallback = pdf_lookalike_text_format(data, filename, at_start=named_as_text(filename))
        if fallback is None:
            raise
        return fallback, EXTRACTORS[fallback](data, options)


def convert_file(path: str | os.PathLike[str], options: ConvertOptions | None = None) -> ConversionResult:
    """Convert the file at `path`. A regular file over `max_file_bytes` is refused from its size before it is read; anything
    else (a pipe, a device) is read only up to the limit (`read_limited`). A path that cannot be opened is an `OSError`."""
    file_path = Path(path)
    _check_arguments(None, options)
    options = options or _DEFAULT_OPTIONS
    with file_path.open("rb") as stream:
        status = os.fstat(stream.fileno())
        if stat.S_ISREG(status.st_mode) and status.st_size > options.max_file_bytes:
            raise DocumentTooLargeError(f"The file is too large (maximum {_size_text(options.max_file_bytes)}).")
        data = read_limited(stream, options.max_file_bytes,
                            size_hint=status.st_size if stat.S_ISREG(status.st_mode) else None)
    return convert(data, file_path.name, options)


async def aconvert(data: bytes | bytearray | memoryview, filename: str | None = None,
                   options: ConvertOptions | None = None, *,
                   executor: Executor | None = None, describer: "ImageDescriber | None" = None,
                   max_concurrency: int = 8) -> ConversionResult:
    """Run `convert` off the event loop and, if there is a `describer`, fill in the images as text.

    Once the character count goes over `options.max_chars`, it stops right there: if the text alone is over, the images are
    neither decoded nor described, and if it goes over during description, the remaining images are not sent. The result's
    `exceeded` tells.
    Without an `executor`, the default thread pool is used. Conversion is mostly pure-Python parsing (PDF, HWP), so it holds the
    GIL for a long time. A server with many concurrent uploads should pass a `ProcessPoolExecutor` to keep other requests
    responsive (the arguments and the result are all picklable).
    Image description is network calls, so they are sent from the event loop `max_concurrency` at a time.
    """
    loop = asyncio.get_running_loop()
    try:
        data = _content_bytes(data)  # a memoryview cannot be sent to a process pool (not picklable)
    except MemoryError as exc:  # the copy, as in `convert`
        raise DocumentTooLargeError(TOO_COMPLEX_MESSAGE) from exc
    _check_arguments(filename, options)
    result = await loop.run_in_executor(executor, partial(convert, data, filename, options))
    if describer is None or not result.images:
        return result

    from opendockit.describe import describe_images

    return await describe_images(result, describer, max_concurrency=max_concurrency)


def render(result: ConversionResult) -> ConversionResult:
    """Put descriptions or placeholder text into the image places of the section originals (template) and render the full text again."""
    options = result.options
    images = {image.id: image for image in result.images}
    pattern = image_marker_pattern(result.marker_key)
    sections = [replace(section, text=_render_template(section.template, images, result.fallbacks, pattern))
                for section in result.sections]

    text = _assemble(sections, options)
    warnings = list(result.base_warnings)
    failed = sum(1 for image in result.images if image.failed)
    if failed:
        warnings.append(f"{failed} image(s) could not be described (the vision model call failed) and were left as placeholder text.")
    unread = [image for image in result.images if image.kind is ImageKind.PAGE and not image.description]
    if unread:
        unread_pages = _pages_holding(result.sections, {image.id for image in unread}, pattern,
                                      [image.section_index for image in unread])
        warnings.append(f"{len(unread_pages)} page(s) whose text exists only as an image ({page_list(unread_pages)}) "
                        "are empty because they did not go through image description (OCR).")

    # Whether the limit is exceeded is counted exactly on the text rendered here. If the extraction stage stopped first, the value
    # counted up to then (counted) is larger than the limit. `result.exceeded` is not simply carried over: before description the
    # result can be over because of the `[Image]` placeholders and then drop under the limit once pictures are removed as decoration.
    char_count = max(len(text), result.counted)
    exceeded = options.max_chars is not None and char_count > options.max_chars
    # Whether nothing was extracted is decided before the cut: with `max_chars=0` text that was cut to nothing was also reported as
    # 'No text was extracted.' (Pinned by: test_audit_core.py::TestWarningsWhenNoCharactersAreAllowed).
    empty = not text.strip()
    if exceeded and options.max_chars is not None:
        text = text[: options.max_chars].rstrip()
        sections, reached = _cut_sections(sections, options, options.max_chars)
        warnings.append(f"The conversion was stopped because the text exceeded {options.max_chars:,} characters.")
    else:
        reached = None
    if empty:
        warnings.append("No text was extracted.")
    return replace(result, text=text, sections=sections, warnings=warnings, exceeded=exceeded, char_count=char_count,
                   reached_sections=reached)


def _prepare_images(raw_images: list[RawImage], sections: list[Section], options: ConvertOptions,
                    warnings: list[str], marker: str) -> tuple[list[DocumentImage], dict[int, str]]:
    """Decode and downscale, filter out small images, repeated images (logos) and duplicates, and build the list of images to
    describe and the placeholder texts.

    An empty placeholder text means the placeholder is removed (decoration). An image to describe gets its description in place
    of the placeholder text.
    """
    fallbacks: dict[int, str] = {}
    prepared = []
    # The same picture (a stamp or logo placed on every page) is decoded only once. Even when the outcome is an exception (dropped,
    # undecodable), it is the same for the same picture (Pinned by: test_image.py::test_same_picture_is_decoded_once).
    decoded: dict[tuple[bytes, bool], tuple[PreparedImage, str] | ImageSkipped | ImageUnreadable] = {}
    # The prepared pictures of one document (downscaled data and tiles, all kept until the end) take at most
    # `max_uncompressed_bytes` together, the per-document bound on decompressed bytes. A re-encoded picture can be far larger
    # than its file: a 4.6 KB PNG of 1-bit noise became a 3 MB JPEG, so a 376 KB DOCX with 300 of them held 920 MB of pictures,
    # pickled once more out of an isolated worker (2.3 GB in the server). Once the next picture does not fit, it and every
    # picture not decoded yet keep only their placeholder (`_placeholders_only`, as past the character limit) with one warning.
    # The first picture prepared is kept whatever its size, so the bound is the option or that one picture.
    # Scanned pages are decoded first, as the image limit picks them first (Pinned by: test_image.py::TestPreparedImageBudget).
    spent = 0
    full = False
    for raw in sorted(raw_images, key=lambda raw: raw.kind is not ImageKind.PAGE):
        # Only a picture inside the body can be a decoration (an icon, a divider). A page rendered because its text is
        # only a picture is the page: at a small `pdf_render_scale` it fell under `min_image_side`, and the page went
        # with it, without the warning that names such pages
        # (Pinned by: test_image.py::TestScannedPageAtASmallScale).
        key = (raw.data, raw.kind is ImageKind.FIGURE)
        if key not in decoded and not full:
            try:
                image = prepare_image(raw.data, min_side=options.min_image_side, max_side=options.image_max_side,
                                      filter_decorations=key[1])
                size = len(image.data) + sum(len(tile) for tile in image.tiles)
                # The first picture prepared is always kept: a single picture is bounded by `image_max_side` already, and
                # an uploaded photo under a lowered option was described before the bound existed
                if spent and spent + size > options.max_uncompressed_bytes:
                    full = True
                    del image
                    continue
                spent += size
                decoded[key] = (image, hashlib.sha256(image.data).hexdigest())
            except (ImageSkipped, ImageUnreadable) as outcome:
                decoded[key] = outcome
            except MemoryError as exc:
                # Not a broken picture but one too large for the memory there is (`image.prepare_image`). A picture that is
                # the document (an uploaded picture, a page of a TIFF) leaves nothing else to give: too large or too complex.
                # A picture inside a document stays as its placeholder, with a warning of its own, and the text is kept: one
                # 13000×13000 RGBA PNG in a DOCX (6.6 MB, under the pixel limit) took the whole document with it under a
                # worker's 2 GB (Pinned by: test_image.py::TestOutOfMemoryWhileReadingAPicture).
                if raw.kind is ImageKind.STANDALONE:
                    raise DocumentTooLargeError(TOO_COMPLEX_MESSAGE) from exc
                # A new one: the one raised holds the frames it went through, and with them the half-read picture. With
                # the raised one gone at the end of this block the picture is freed at once — a Pillow picture is part of
                # no reference cycle, so no collection is run: a full one after every such picture costs with the heap
                # of the process (500 small pictures 6.5 s for 0.2 s, and 55 s in a process holding 3 million objects)
                # (Pinned by: test_image.py::TestOutOfMemoryWhileReadingAPicture::test_what_is_left_of_a_picture_is_released_before_the_next_one).
                decoded[key] = ImageOutOfMemory()

    past: list[RawImage] = []  # pictures past the budget of prepared bytes: not kept (the one that did not fit was let go of)
    for raw in raw_images:
        alt = _alt_text(raw)
        outcome = decoded.get((raw.data, raw.kind is ImageKind.FIGURE))
        if outcome is None:
            past.append(raw)
            continue
        if isinstance(outcome, ImageTooLarge) and raw.kind is ImageKind.STANDALONE:
            # A size problem, not corruption. A very large picture that cannot be read reduced (not a JPEG, or over the decode
            # limit even at 1/8) (Pinned by: test_core_image_and_assembly.py::TestVeryLargePictures).
            raise DocumentTooLargeError("The image is too large (decode limit about 179 million pixels). Reduce its resolution or "
                                        "save it as JPEG and upload it again.") from outcome
        if isinstance(outcome, ImageUnreadable) and raw.kind is ImageKind.STANDALONE:
            # The uploaded file is that one picture. Reject it like any other corrupted file — it used to come back as a success
            # whose body was just '[Image]'
            # (Pinned by: test_image.py::TestStandaloneImage::test_uploaded_image_that_cannot_be_decoded_is_rejected_as_corrupted).
            if needs_heif_plugin(raw.data):
                raise UnsupportedFormatError('Reading HEIC/HEIF images needs an optional dependency. '
                                             'Install it with: pip install "opendockit[heic]"') from outcome
            message = "Could not read the image. The file may be corrupted or may be an unsupported image format."
            raise CorruptedDocumentError(message) from outcome
        if isinstance(outcome, ImageSkipped):
            fallbacks[raw.id] = ""
        elif isinstance(outcome, ImageUnreadable):
            fallbacks[raw.id] = _image_fallback(alt)
        else:
            prepared.append((raw, alt, *outcome))

    # A picture that could not be decoded remains only as placeholder text. Say that content is missing (the same picture is counted
    # once). Pictures left out for being too large are reported separately — reported as 'WMF/EMF or corrupted', nobody could tell it
    # was the size (Pinned by: test_core_mbox_markdown_and_api.py::TestTooLargePictureInsideADocument).
    too_large = sum(1 for outcome in decoded.values() if isinstance(outcome, ImageTooLarge))
    out_of_memory = sum(1 for outcome in decoded.values() if isinstance(outcome, ImageOutOfMemory))
    unreadable = sum(1 for outcome in decoded.values() if isinstance(outcome, ImageUnreadable)) - too_large - out_of_memory
    if out_of_memory and not prepared and not _has_text(sections, marker):
        # Scanned pages that are the only content, none of which could be read: nothing else to give either.
        raise DocumentTooLargeError(TOO_COMPLEX_MESSAGE)
    fallbacks.update(_placeholders_only(past, options))
    if unreadable:
        warnings.append(f"{unreadable} image(s) are in an unreadable format (WMF/EMF vectors, etc.) or corrupted "
                        "and were left as placeholder text.")
    if too_large:
        warnings.append(f"{too_large} image(s) are too large (decode limit about 179 million pixels) and were left as placeholder text.")
    if out_of_memory:
        warnings.append(f"{out_of_memory} image(s) were too large to process in the memory available and were left as placeholder text.")

    counts: dict[str, int] = {}
    for _, _, _, digest in prepared:
        counts[digest] = counts.get(digest, 0) + 1

    candidates: list[tuple[RawImage, str | None, PreparedImage]] = []
    first_of: dict[str, int] = {}
    aliases: dict[int, int] = {}

    for raw, alt, image, digest in prepared:
        if raw.kind is ImageKind.FIGURE and counts[digest] >= options.repeated_image_threshold:
            fallbacks[raw.id] = ""
            continue
        if digest in first_of:
            # The same picture appearing again below the repeat threshold is switched to the first one's placeholder, so it is
            # described once and the description goes into both places. The second place used to be erased and the picture
            # vanished from that page or slide (Pinned by: test_image.py::TestSamePictureTwice).
            # If the first one has no alt text, the alt text of the later one is used.
            index = first_of[digest]
            first, first_alt, first_image = candidates[index]
            aliases[raw.id] = first.id
            candidates[index] = (first, first_alt or alt, first_image)
            continue
        first_of[digest] = len(candidates)
        candidates.append((raw, alt, image))

    for raw, alt, _ in candidates:
        fallbacks[raw.id] = "" if raw.kind is ImageKind.PAGE else _image_fallback(alt)

    if aliases:
        _point_aliases_at_first(sections, aliases, marker)

    # Over the limit, whole-page images (scanned pages — the only content of that page) are picked before pictures.
    chosen = {raw.id for raw, _, _ in sorted(candidates, key=lambda item: item[0].kind is not ImageKind.PAGE)
              [: options.max_images]}
    locations = _locate_markers(sections, image_marker_pattern(marker))
    images: list[DocumentImage] = []
    left_page_ids: list[int] = []
    left_figures = 0
    for raw, alt, image in candidates:
        section, context = locations.get(raw.id, (None, ""))
        if raw.id not in chosen:
            if raw.kind is ImageKind.PAGE:
                left_page_ids.append(raw.id)
            else:
                left_figures += 1
            continue
        images.append(DocumentImage(
            id=raw.id, data=image.data, mime_type=image.mime_type, width=image.width, height=image.height, tiles=image.tiles,
            kind=raw.kind, section_kind=section.kind if section else SectionKind.DOCUMENT,
            section_index=section.index if section else 1, alt=alt, context=context,
        ))

    # A page image left out by the limit leaves its page empty (its placeholder text is empty), so it is not counted among the
    # pictures 'left as placeholders' and its pages are named, as `render` names the pages that were not described. Counted
    # with the pictures, the warning said every one had kept a placeholder and never named the empty pages
    # (Pinned by: test_image.py::TestScannedPagesLeftOutByTheImageLimit).
    left_pages = _pages_holding(sections, set(left_page_ids), image_marker_pattern(marker),
                                [locations[image_id][0].index if image_id in locations else 1 for image_id in left_page_ids])
    if left_pages:
        figures = f", and {left_figures} other image(s) were left as placeholders only" if left_figures else ""
        warnings.append(f"There are many images, so only {options.max_images} were selected for description (scanned pages first). "
                        f"{len(left_pages)} page(s) whose text exists only as an image ({page_list(left_pages)}) were left out "
                        f"and are empty{figures}.")
    elif left_figures:
        warnings.append(f"There are many images, so only {options.max_images} were selected for description (scanned pages first) "
                        f"and {left_figures} were left as placeholders only.")
    warning = _past_budget_warning(past, fallbacks, locations)
    if warning:
        warnings.append(warning)
    return images, fallbacks


def _past_budget_warning(past: list[RawImage], fallbacks: dict[int, str],
                         locations: dict[int, tuple[Section, str]]) -> str | None:
    """The one warning for the pictures left out by the budget of prepared bytes. Each picture is counted once (by its bytes);
    a scanned page left out is empty and named, as for the image limit; a picture that leaves nothing (a logo, a divider) is
    not counted, and with nothing to count there is no warning."""
    pages = sorted({locations[raw.id][0].index if raw.id in locations else 1 for raw in past if raw.kind is ImageKind.PAGE})
    figures = len({raw.data for raw in past if raw.kind is not ImageKind.PAGE and fallbacks.get(raw.id)})
    start = "The images take too much memory once prepared (more than max_uncompressed_bytes), so "
    if not pages:
        return f"{start}{figures} image(s) were left as placeholders only." if figures else None
    others = f", and {figures} other image(s) were left as placeholders only" if figures else ""
    return (f"{start}{len(pages)} page(s) whose text exists only as an image ({page_list(pages)}) were left out and are "
            f"empty{others}.")


def _alt_text(raw: RawImage) -> str | None:
    """The author's alt text of a picture as one clean line, or None when there is none or it is one Office or Hangul (HWP)
    wrote itself (`_USELESS_ALT`, `_is_file_name`)."""
    # Placeholder text goes in after cleaning (clean_text), so it is cleaned into one line here. NFD and line breaks stayed as
    # they were and broke table rows. It is written inside `[Image: …]`, so like a section title it is cleaned as one line
    # and not as a text whose first line may open a fence.
    # The patterns are matched on the alt text cleaned the same way (`markdown.clean_characters`: NFC, removed characters gone) but
    # with its line breaks, which the Office trailer is told by. Matched as the file wrote it, '그림 3' in decomposed jamo or with a
    # zero-width space was kept as '[Image: 그림 3]' and sent to the describer, while composed it was dropped
    # (Pinned by: test_image.py::TestOfficeAutoGeneratedAltText::test_auto_generated_alt_text_is_dropped_in_any_normalization).
    if not raw.alt:
        return None
    alt = clean_characters(raw.alt).strip()
    return clean_line(raw.alt) if not _USELESS_ALT.match(alt) and not _is_file_name(alt) else None


def _is_file_name(alt: str) -> bool:
    """Whether alt text is only the file name of a picture (`_IMAGE_FILE_NAME`), not a sentence that ends in one."""
    if not _IMAGE_FILE_NAME.fullmatch(alt):
        return False
    name = alt
    folders = _FOLDERS.match(alt)
    if folders is not None and (_PATH_START.match(alt) or not any(character.isspace() for character in folders.group(1))):
        name = alt[folders.end():]
    if _SENTENCE_PUNCTUATION.search(_DATE_ABBREVIATION.sub(r"\1", name)):
        return False
    words = len(name.split())
    return words <= _FILE_NAME_WORDS or (words <= _DATED_FILE_NAME_WORDS and any(character.isdigit() for character in name))


def _placeholders_only(raw_images: list[RawImage], options: ConvertOptions) -> dict[int, str]:
    """The placeholder texts of the pictures of a document whose text alone is over the limit, without decoding any of them.

    Each gets what `_prepare_images` gives a picture that is not described: `[Image: alt]` (or `[Image]`), nothing for a
    scanned page, nothing for a picture repeated `repeated_image_threshold` times or more (a logo; told here by its bytes),
    and the same picture the first alt text among its copies. With no placeholder texts at all every picture before the cut
    vanished, the author's alt text with it and without a warning, while a document over the limit only once whitespace was
    counted kept them: a long DOCX lost '[Image: Quarterly revenue chart]' at `max_chars=1000`, and the MCP server (100,000 by
    default) never showed a picture of a long document
    (Pinned by: test_converter.py::TestLimits::test_pictures_before_the_cut_keep_their_placeholder_when_the_text_alone_is_over).

    What decoding would do is read from the picture's header (`image.header_size`, no pixel decoded). A picture too small or
    too thin to carry information gets nothing, as decoding drops it (`image.is_decoration`, the test of `prepare_image`): a
    divider or an icon left `[Image]` in the cut text where the full conversion has none
    (Pinned by: test_converter.py::TestLimits::test_pictures_that_decoding_drops_leave_nothing_past_the_limit). A picture
    whose header cannot be read in a format that is read (WMF/EMF vectors, a HEIC without its extra, garbage) or that is over
    the decode limit is one `_prepare_images` cannot decode: it keeps its own alt text and is never taken for a logo, as
    there. Counted with the others, three copies of a WMF vanished as a logo and a copy took the alt text of another
    (Pinned by: test_converter.py::TestLimits::test_pictures_that_cannot_be_decoded_keep_their_own_placeholder_past_the_limit).

    Known accepted gaps: a file whose header reads but whose pixels are broken keeps the placeholder of a readable picture;
    copies are told by their bytes, not by the decoded picture; and what the full conversion takes from the pictures past
    the stop is not known here, as they are never read: a logo with fewer copies before the stop than
    `repeated_image_threshold` keeps `[Image]` at those copies, and a copy without alt text does not get the alt text of a
    later copy (`_prepare_images` gives the first copy the first alt text among all of them).
    """
    sizes: dict[bytes, tuple[int, int] | None] = {}
    counts: dict[bytes, int] = {}
    alts: dict[bytes, str | None] = {}
    fallbacks: dict[int, str] = {}
    for raw in raw_images:
        if raw.data not in sizes:
            sizes[raw.data] = header_size(raw.data, options.image_max_side)
        size = sizes[raw.data]
        if size is None:
            fallbacks[raw.id] = _image_fallback(_alt_text(raw))
        elif raw.kind is ImageKind.FIGURE and is_decoration(*size, min_side=options.min_image_side):
            fallbacks[raw.id] = ""
        else:
            counts[raw.data] = counts.get(raw.data, 0) + 1
            alts[raw.data] = alts.get(raw.data) or _alt_text(raw)
    for raw in raw_images:
        if raw.id in fallbacks:
            continue
        logo = raw.kind is ImageKind.FIGURE and counts[raw.data] >= options.repeated_image_threshold
        fallbacks[raw.id] = "" if raw.kind is ImageKind.PAGE or logo else _image_fallback(alts[raw.data])
    return fallbacks


def _has_text(sections: list[Section], marker: str) -> bool:
    """Whether the document holds anything besides picture placeholders: a section title or body text."""
    pattern = image_marker_pattern(marker)
    return any(section.title or pattern.sub("", section.template).strip() for section in sections)


def page_list(numbers: list[int]) -> str:
    """Page numbers for a warning: the first 10, then 'and more'."""
    shown = ", ".join(str(number) for number in numbers[:10])
    return f"{shown} and more" if len(numbers) > 10 else shown


def _point_aliases_at_first(sections: list[Section], aliases: dict[int, int], marker: str) -> None:
    """Among the placeholders in the section originals, change the numbers in `aliases` to the number of the first occurrence of the
    same picture. The limit decision during description counts the placeholder occurrences and multiplies the bound on the
    increase by that (`describe.describe_images`), so both places are counted."""
    pattern = image_marker_pattern(marker)
    with marker_key(marker):
        def point(match: re.Match[str]) -> str:
            image_id = int(match.group(1))
            return image_marker(aliases[image_id]) if image_id in aliases else match.group(0)

        for index, section in enumerate(sections):
            sections[index] = replace(section, template=pattern.sub(point, section.template))


def _pages_holding(sections: list[Section], image_ids: set[int], pattern: re.Pattern[str], also: list[int]) -> list[int]:
    """The numbers of the sections whose original holds the placeholder of one of `image_ids`, with `also` (the section each
    picture was found in), in order and once each.

    A copy of a picture points at the first one (`_point_aliases_at_first`), so a scan whose pages are the same picture is one
    image placed on every page. Counted by the images, 100 such pages left empty were '10 page(s)', naming 10 of them
    (Pinned by: test_image.py::TestPdfImages::test_identical_scanned_pages_are_each_counted)."""
    pages = set(also)
    if not image_ids:
        return sorted(pages)
    for section in sections:
        if any(int(match.group(1)) in image_ids for match in pattern.finditer(section.template)):
            pages.add(section.index)
    return sorted(pages)


def _locate_markers(sections: list[Section], pattern: re.Pattern[str]) -> dict[int, tuple[Section, str]]:
    """Image id → (the section it is in, part of the body text right before it).

    The preceding text is built by joining the text between placeholders and carrying only the tail. Rescanning the whole front
    of the section for every placeholder takes (number of pictures × body length) on a single-section document with many
    pictures (HWP, DOCX) (19 seconds for 16,384 pictures).
    """
    locations = {}
    for section in sections:
        tail, position = "", 0
        for match in pattern.finditer(section.template):
            tail = (tail + section.template[position:match.start()])[-_CONTEXT_WINDOW:]
            position = match.end()
            locations.setdefault(int(match.group(1)), (section, tail.strip()[-_CONTEXT_CHARS:]))  # first place, if the picture appears several times
    return locations


def _render_template(template: str, images: dict[int, DocumentImage], fallbacks: dict[int, str],
                     pattern: re.Pattern[str]) -> str:
    if "⟦IMG:" not in template:
        return template

    lines: list[str] = []
    fenced = _fenced_lines(template)
    source = template.split("\n")
    for index, line in enumerate(source):
        ids = [int(found) for found in pattern.findall(line)]
        if not ids:
            lines.append(_FENCED_LINE + line if index in fenced else line)
            continue
        # A line inside a quote (`> `, `> > `) is looked at without its quote marks, and what goes in keeps them. Looked at
        # whole, a row of a quoted table (`> | Kim | ⟦IMG⟧ |`) was not a table row: the picture was cut out of its cell and
        # its block put on lines of its own outside the quote, which broke the table and the quote in two; in a quoted
        # paragraph the block landed outside the quote (Pinned by: test_converter.py::TestPicturesInsideAQuote).
        prefix, content = "", line
        if ">" in line:
            _, depth, content = _split_quote(line)
            prefix = line[: len(line) - len(content)] if depth else ""
        row = content.strip()
        markup = row.startswith("<tr>") and row.endswith("</tr>")
        if markup or (len(row) > 1 and row.startswith("|") and row.endswith("|")):
            # Inside a table cell: a table row has to be one line, so fold it into one line. An HTML table (a table with merged
            # cells, markdown.TableGrid) is escaped as HTML. A table row is recognized only as a line that starts and ends with `|`
            # (the `| … |` of render_table/TableGrid, and `|a|b|` with no spaces around the cells in a Markdown source) or as
            # `<tr>…</tr>`. Looking at the start only, a paragraph starting with `|` or `<tr>` was read as a table row and the
            # picture description was folded onto one line
            # (Pinned by: test_converter.py::TestAuditedAssemblyGaps::test_paragraph_that_starts_like_a_table_row_gets_a_picture_block).
            # Looking only for lines ending in `… |`, a picture in a Markdown `|a|b|` table cell became a paragraph picture and
            # the table broke in two (Pinned by: test_core_text_and_mail.py::TestPictureInACompactMarkdownTable).
            # Known accepted gap: a paragraph of the form `|…|` is still a table row.
            lines.append(pattern.sub(lambda match: _cell_text(images, fallbacks, int(match.group(1)), html=markup), line))
            continue

        # Inside a paragraph (or on a line of its own): leave the text as it is and put the image block below it. The placeholder,
        # together with the spaces around it, becomes one space, the leading indentation of the line (the nested-list level) is
        # kept, and a blank line follows the block — without it the next line continued into the quote block
        # (Pinned by: test_converter.py::TestAssembly::test_picture_block_inside_a_paragraph_is_followed_by_a_blank_line,
        # test_picture_in_nested_list_item_keeps_the_item_indentation).
        # The line is cut at the placeholders and the spaces are stripped from the pieces: one pattern for 'spaces, placeholder,
        # spaces' started again at every space of a run, so a line with 80,000 spaces before a picture took 4 seconds
        # (Pinned by: test_audit_core.py::TestSpacesOnALineWithAPicture).
        pieces, position = [], 0
        for match in pattern.finditer(content):
            pieces.append(content[position:match.start()])
            position = match.end()
        body = " ".join(piece.strip(" ") for piece in [*pieces, content[position:]]).strip()
        text = prefix + content[: len(content) - len(content.lstrip())] + body if body else ""
        blocks = [block for block in (_block_text(images, fallbacks, image_id) for image_id in ids) if block]
        # Inside a code block the blank line after the block goes in only before a line of code: the blank lines of the code
        # after it stay as written (they are not collapsed), so the one of the block came on top of them — two blank lines
        # became three — and one went in before the closing fence
        # (Pinned by: test_core_image_and_assembly.py::TestBlankLinesInCodeNextToAPicture::
        # test_picture_inside_a_code_block_adds_no_blank_line_of_its_own).
        gap = index not in fenced or (index + 1 in fenced and _split_quote(source[index + 1])[2].strip() != "")
        if prefix:
            lines.append(_quoted_blocks(prefix, text, blocks, gap=gap))
            continue
        lines.append("\n\n".join(part for part in [text, *blocks] if part) + ("\n" if blocks and gap else ""))
    rendered = "\n".join(lines)
    if _QUOTE_GAP in rendered:
        rendered = _settle_quote_gaps(rendered)
    return _collapse_blank_lines(rendered).strip()


# A mark attached during rendering to the empty quote line (`>`) that follows a picture block inside a quote, or that stands for
# a quoted line left with nothing (a private-use character — `clean_text` has already removed it, so it is not in the body).
_QUOTE_GAP = "\ue031"


def _quoted_blocks(prefix: str, text: str, blocks: list[str], *, gap: bool = True) -> str:
    """The rendering of a quoted line holding pictures: as outside a quote, but every line of the picture blocks gets the quote
    marks of the line (`prefix`, a description becoming a quote in the quote) and the blank lines around them are empty quote
    lines, so the block stays in the quote. The empty line after the blocks, or the whole line when nothing is left of it, is
    an empty quote line marked `_QUOTE_GAP` that `_settle_quote_gaps` keeps only between two lines with text: next to the empty
    quote line that already separates two quoted paragraphs (or a SKIP answer that left the line empty) it left a stray `>`
    (Pinned by: test_converter.py::TestPicturesInsideAQuote). Without `gap` (a line inside a code block not followed by a line
    of code) there is no empty line after the blocks."""
    blank = prefix.rstrip()
    parts = [text] if text else []
    parts += ["\n".join(prefix + line if line.strip() else blank for line in block.split("\n")) for block in blocks]
    rendered = f"\n{blank}\n".join(parts)
    if (blocks and gap) or not (text or blocks):
        rendered = (rendered + "\n" if rendered else "") + _QUOTE_GAP + blank
    return rendered


def _settle_quote_gaps(text: str) -> str:
    """Keep an empty quote line marked `_QUOTE_GAP` only where it separates two lines with text, and drop the others: at the start
    or end of the section, or next to an empty line or another empty quote line no deeper than it. A run of them is kept once.
    A quoted line left with nothing (a picture answered SKIP on a line of its own) also takes one of the two empty lines around
    it, as two blank lines become one outside a quote: the empty quote lines before and after it are kept once, and one before
    the end of the quote is dropped. It only removes lines, and at most one line of the text besides the marked ones for each
    picture, which `image_length_bound` counts."""
    source = text.split("\n")
    kept: list[str] = []
    skip = -1
    for index, line in enumerate(source):
        if index == skip:
            continue
        if not line.startswith(_QUOTE_GAP):
            kept.append(line)
            continue
        gap = line[len(_QUOTE_GAP):]
        depth = _split_quote(gap)[1]
        following = source[index + 1] if index + 1 < len(source) else None
        after = following is not None and _is_separator(following, depth)
        if not kept or _is_separator(kept[-1], depth):
            if after and following.strip() and not following.startswith(_QUOTE_GAP):
                skip = index + 1
            elif kept and kept[-1].strip() and (following is None or not following.strip()):
                kept.pop()
        elif following is not None and not after:
            kept.append(gap)
    return "\n".join(kept)


def _is_separator(line: str, depth: int) -> bool:
    """Whether `line` already separates blocks for an empty quote line `depth` marks deep: an empty line, a `_QUOTE_GAP` line or
    an empty quote line with at most `depth` marks."""
    if not line.strip() or line.startswith(_QUOTE_GAP):
        return True
    if ">" not in line:
        return False
    _, marks, content = _split_quote(line)
    return 0 < marks <= depth and not content.strip()


# A mark attached during rendering to lines inside a code fence (a private-use character — `clean_text` has already removed it,
# so it is not in the body).
_FENCED_LINE = "\ue030"


def _fenced_lines(template: str) -> set[int]:
    """Line numbers inside paired code fences (``` or ~~~). Pairing is `markdown.code_fences`, the one `clean_text` uses (what
    follows an unpaired opening fence is outside). Both characters are paired in every format: in a document that is not
    Markdown `clean_text` has neutralized every line that would open a tilde fence, so the code blocks found here are the
    ones it saw — a picture between two lines of tildes is not inside code
    (Pinned by: test_markdown.py::TestFencesThatAreText::test_picture_between_two_tilde_lines_is_not_inside_code)."""
    return code_fences(template.split("\n")).inside


def _collapse_blank_lines(text: str) -> str:
    """Reduce runs of two or more blank lines to one, but leave the lines inside a code fence (marked `_FENCED_LINE`) as they are
    and remove the mark.

    `\\n{3,}` → `\\n\\n` was applied to the whole section, so only in sections holding a picture the consecutive blank lines inside
    a code block that `clean_text` had kept (two lines between functions) were reduced to one
    (Pinned by: test_core_image_and_assembly.py::TestBlankLinesInCodeNextToAPicture). It only reduces, so the character bound
    (`image_length_bound`) still holds.
    """
    lines: list[str] = []
    for line in text.split("\n"):
        if line.startswith(_FENCED_LINE):
            lines.append(line[len(_FENCED_LINE):])
        elif line or not lines or lines[-1]:
            lines.append(line)
    return "\n".join(lines)


def image_length_bound(image: DocumentImage, fallbacks: dict[int, str], quote: int = 0) -> int:
    """The most the character count of `render` can grow when this picture goes from the erased (decorative) state to its current state.

    A placeholder becomes a block (`_block_text`) in a paragraph and one line (`_cell_text`) in a table cell, and gets one blank
    line before the block (2 characters) and the line break that makes the blank line after it (1 character). Merging blank
    lines and trimming surrounding whitespace only reduce the count. When the placeholder of one picture appears several times,
    the caller multiplies by the count. `describe` uses this value to skip rendering the document, so if it were smaller than
    the real value, an exceeded limit would be missed
    (Pinned by: test_image.py::TestResourceBounds::test_description_stops_at_exactly_the_image_that_crosses_the_limit).
    A picture that is erased now (decorative, no alt text) has not grown at all: 0. Counted as the 3 characters of the blank
    lines it no longer has, every SKIP answer used up headroom, so in a document just under the limit the whole text was
    assembled again every few pictures — quadratic in the number of pictures, on the event loop (2,000 pictures: 2.6 s)
    (Pinned by: test_core_image_and_assembly.py::TestDecorativeAnswersNearTheLimit).
    Inside a quote (`quote`, the length of the longest quote marks before the placeholder, `quote_widths`) every line of the
    block gets those marks, and the blank lines around it and the one a neighbouring empty quote line may now keep
    (`_settle_quote_gaps`) are empty quote lines: the marks are counted once per line of the block and three more times.
    Without them the bound was short by the marks, and the stop during description could miss the limit
    (Pinned by: test_converter.py::TestPicturesInsideAQuote::test_description_stops_at_exactly_the_image_that_crosses_the_limit).
    """
    if _erased(image):
        return 0
    images = {image.id: image}
    block = _block_text(images, fallbacks, image.id)
    return max(len(block) + quote * (block.count("\n") + 4), len(_cell_text(images, fallbacks, image.id)),
               len(_cell_text(images, fallbacks, image.id, html=True))) + 3


def quote_widths(sections: list[Section], pattern: re.Pattern[str]) -> dict[int, int]:
    """Image id → the length of the longest quote marks (`> `, `> > `) on any line of its section that holds a placeholder,
    for the pictures of the sections that have a placeholder inside a quote (`image_length_bound`). The line start is carried
    from one placeholder to the next, so a long line with many pictures is read once.

    The widest of the section, not that of the picture's own line: whether the empty quote line after a picture is kept
    depends on the line after it (`_settle_quote_gaps`), which may hold another picture, so describing a picture outside the
    quote (`> ![](A)` followed by `![](B)`, a lazy continuation in Markdown) brought back the empty quote line of the
    picture before it, which a SKIP answer had dropped, and the stop during description ran past the limit (Pinned by:
    test_converter.py::TestPicturesInsideAQuote::test_a_picture_after_a_quoted_one_counts_the_quote_marks_of_its_neighbour)."""
    widths: dict[int, int] = {}
    for section in sections:
        template = section.template
        start, position, width, widest = 0, 0, 0, 0
        found: list[int] = []
        for match in pattern.finditer(template):
            newline = template.rfind("\n", position, match.start())
            if newline >= 0 or position == 0:
                start = newline + 1
                head = template[start:match.start()]
                width = len(head) - len(_split_quote(head)[2]) if ">" in head else 0
            position = match.end()
            widest = max(widest, width)
            found.append(int(match.group(1)))
        if widest:
            for image_id in found:
                widths[image_id] = max(widths.get(image_id, 0), widest)
    return widths


def _erased(image: DocumentImage | None) -> bool:
    """Whether this picture was judged decorative and is to be erased from its place. If the author attached alt text, it is not
    erased and the placeholder text ('[Image: …]') stays — it is information a person wrote
    (Pinned by: test_image.py::TestDecorativePictureWithAltText)."""
    return image is not None and image.decorative and not image.alt


def _image_fallback(alt: str | None) -> str:
    """`[Image: alt]` (or `[Image]`) for a picture that stays as placeholder text. The brackets of the alt text are escaped like link
    text (`_inline._escape_link_text`), as the extractors do for pictures they do not extract: an alt such as
    `a](https://evil.example) [b` made the placeholder a working link (Pinned by:
    test_audit_web_fixes.py::TestAltTextCannotMakeALink::test_alt_text_of_an_extracted_picture). The describer still gets the alt
    text as written."""
    return f"[Image: {_escape_link_text(alt)}]" if alt else "[Image]"


def _block_text(images: dict[int, DocumentImage], fallbacks: dict[int, str], image_id: int) -> str:
    image = images.get(image_id)
    if image is None or not image.description:
        return "" if _erased(image) else fallbacks.get(image_id, "")
    if image.kind is ImageKind.PAGE:
        return f"<!-- Text read from image -->\n{image.description}"
    lines = image.description.split("\n")
    lines[0] = f"[Image] {lines[0]}"
    return "\n".join(f"> {line}" if line.strip() else ">" for line in lines)


def _cell_text(images: dict[int, DocumentImage], fallbacks: dict[int, str], image_id: int, *, html: bool = False) -> str:
    """The text of a picture inside a table cell (one line). In a Markdown cell `|` separates cells, so it becomes `\\|`
    (Pinned by: test_converter.py::TestAssembly::test_alt_text_is_escaped_in_table_cells_and_normalized); in an HTML cell only
    the table tags are neutralized, as for cell text (test_picture_in_an_html_table_cell_keeps_its_text)."""
    image = images.get(image_id)
    if image is None or not image.description:
        lines = ["" if _erased(image) else fallbacks.get(image_id, "")]
    else:
        lines = [line.strip() for line in image.description.split("\n") if line.strip()] or [""]
        lines[0] = f"[Image] {lines[0]}"
    if html:
        return "<br>".join(neutralize_table_tags(line) for line in lines)
    return "<br>".join(lines).replace("|", "\\|")


def _guard_zip(data: bytes, options: ConvertOptions) -> None:
    """Zip-bomb defense: check the total uncompressed size first, from the central directory."""
    try:
        total = uncompressed_size(data)
    except zipfile.BadZipFile as exc:
        raise CorruptedDocumentError("The document's archive structure is corrupted.") from exc
    if total > options.max_uncompressed_bytes:
        raise DocumentTooLargeError("The document becomes too large when decompressed.")


def _assemble(sections: list[Section], options: ConvertOptions) -> str:
    return _layout(sections, options)[0].strip()


def _layout(sections: list[Section], options: ConvertOptions) -> tuple[str, list[int]]:
    """The text of the joined sections (before the surrounding whitespace is trimmed) and where each section body starts in it."""
    parts: list[str] = []
    starts: list[int] = []
    position = 0

    for section in sections:
        header = _header(section, options)
        part = "\n\n".join(piece for piece in (header, section.text) if piece)
        if part and parts:
            position += 2
        starts.append(position + (len(part) - len(section.text)))
        if part:
            parts.append(part)
            position += len(part)

    return "\n\n".join(parts), starts


def _header(section: Section, options: ConvertOptions) -> str:
    if section.kind is SectionKind.PAGE:
        return f"<!-- Page {section.index} -->" if options.page_markers else ""
    return section_heading(section)


def section_heading(section: Section) -> str:
    """The heading the full text gives a slide or a sheet (`## Slide 2: Goals`, `## Sheet: Sales`); '' for a page or a whole
    document. For callers that hand out sections one by one (the integrations) and want each to say what it is."""
    if section.kind is SectionKind.SLIDE:
        return f"## Slide {section.index}" + (f": {section.title}" if section.title else "")
    if section.kind is SectionKind.SHEET:
        return f"## Sheet: {section.title}" if section.title else f"## Sheet {section.index}"
    return ""


def _cut_sections(sections: list[Section], options: ConvertOptions, limit: int) -> tuple[list[Section], int]:
    """Cut the section bodies at the same point where `text` was cut for going over the limit, and count the sections the cut
    text reaches. The body of a section that starts after the cut is empty text.

    Over the limit, only `text` was cut and everything stayed in `sections`, so code using the sections (chunking, source
    attribution) received content beyond the limit
    (Pinned by: test_converter.py::TestAuditedAssemblyGaps::test_sections_are_cut_where_the_text_is_cut and 2 more). The section
    list and `template` are left as they are — when descriptions are filled in again, `render` renders from the originals and
    counts the characters again.

    A section is reached when its whole heading is in the text (a slide, a sheet, a page with its marker), or, without a
    heading, the start of its body. A slide past the cut keeps its title and has no body, like a slide that is only a title:
    only the count tells them apart (`ConversionResult.reached_sections`; Pinned by:
    test_integrations.py::TestLangChainLoader::test_sections_past_the_character_limit_give_no_piece).
    """
    joined, starts = _layout(sections, options)
    cut = len(joined) - len(joined.lstrip()) + limit
    reached = 0
    for section, start in zip(sections, starts, strict=True):
        heading = _header(section, options)
        heading_end = start - 2 if heading and section.text else start   # the body follows its heading after a blank line
        if (heading_end > cut) if heading else (start >= cut):
            break
        reached += 1
    return [replace(section, text=section.text[:max(cut - start, 0)].rstrip())
            for section, start in zip(sections, starts, strict=True)], reached
